  def("8", ".###. #...# #...# .###. #...# #...# .###.");
  def("9", ".###. #...# #...# .#### ....# ...#. .##..");
  // lowercase (7 rows + optional 2 descender rows)
  def("a", "..... ..... .###. ....# .#### #...# .####");
  def("b", "#.... #.... #.##. ##..# #...# #...# ####.");
  def("c", "..... ..... .###. #.... #.... #...# .###.");
