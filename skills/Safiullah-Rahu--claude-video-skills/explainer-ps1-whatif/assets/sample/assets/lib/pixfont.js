  def("V", "#...# #...# #...# #...# #...# .#.#. ..#..");
  def("W", "#...# #...# #...# #.#.# #.#.# #.#.# .#.#.");
  def("X", "#...# #...# .#.#. ..#.. .#.#. #...# #...#");
  def("Y", "#...# #...# .#.#. ..#.. ..#.. ..#.. ..#..");
  def("Z", "##### ....# ...#. ..#.. .#... #.... #####");
  // digits
  def("0", ".###. #...# #..## #.#.# ##..# #...# .###.");
  def("1", "..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.");
  def("2", ".###. #...# ....# ...#. ..#.. .#... #####");
  def("3", "####. ....# ....# .###. ....# ....# ####.");
  def("4", "...#. ..##. .#.#. #..#. ##### ...#. ...#.");
