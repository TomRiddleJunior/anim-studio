"""Build the choice-night-story project from the voice-over:
  assets/lib/vo-data.js     word times (window.NS_VO) for film.js
  compositions/captions.html  the source's caption system: 1-3 word CAPS phrases (Oswald 700), centred at 73 % of the
                              height, white with a soft drop shadow; keywords yellow (#f5b52e) or red (#ef5a4a) from the
                              script's "kw" map; lines spoken by another character carry a small speaker tag above the
                              phrase (script "tags": who -> [label, colour]); the "voice"/radio character's phrases are amber
  compositions/world.html   the canvas world (ns-kit.js + film.js), seek-exact
  index.html                1080 x 1920, 30 fps, root duration = the voice-over duration
  out/<name>.srt            every spoken phrase (for WPM in the QA)

usage: python -X utf8 -I tools/build.py        (after tts.py has written vo/data/vo.json)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
SPEC = json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))
BY = {l["id"]: l for l in SPEC["lines"]}
TAGS = SPEC.get("tags", {})
DUR = round(VO["duration"], 2)
CAP_Y = 1400          # caption centre: 73 % of the height (source: 73 %)
CAP_PX = 76           # source: ~25 px Oswald Bold on a 360-wide view -> ~76 px at 1080
COL = {"y": "#f5b52e", "r": "#ef5a4a", "w": "#ffffff", "a": "#ffd27a"}


def norm(s):
    return re.sub(r"[^a-z0-9'\-]", "", s.lower()).strip("-")


EMPH = set()


def phrases(words):
    """1-3 word phrases (<= 18 characters), always breaking after , . ? ! ; : … — the source's rhythm."""
    out, cur = [], []
    for k, w in enumerate(words):
        cur.append(w)
        txt = " ".join(x["w"] for x in cur)
        nxt = words[k + 1] if k + 1 < len(words) else None
        long_next = nxt is not None and len(txt) + 1 + len(nxt["w"]) > 18
        if re.search(r"[,.?!;:…]$", w["w"]) or len(cur) >= 3 or long_next:
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    # a lone plain word ("WOULD.", "IN.") borrows the last word of an unpunctuated phrase before it; emphatic singles
    # (keywords, "KID!") stay alone, as in the format
    for i in range(1, len(out)):
        prev, cur_ = out[i - 1], out[i]
        if len(cur_) == 1 and len(prev) >= 2 and not re.search(r"[,.?!;:…]$", prev[-1]["w"]) and norm(cur_[0]["w"]) not in EMPH                 and not cur_[0]["w"].endswith("!"):
            out[i] = [prev.pop()] + cur_
    # merge a lone unpunctuated short word into the next phrase when it fits
    fixed = []
    for p in out:
        if fixed and len(fixed[-1]) == 1 and not re.search(r"[,.?!;:…]$", fixed[-1][-1]["w"]) and len(" ".join(x["w"] for x in fixed[-1] + p)) <= 20 and len(fixed[-1] + p) <= 3:
            fixed[-1] = fixed[-1] + p
        else:
            fixed.append(p)
    return fixed


def main():
    lines = VO["lines"]
    vo_js = {"duration": DUR, "lines": {l["id"]: {"start": l["start"], "end": l["end"], "who": BY[l["id"]].get("who", "narrator"),
                                                  "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]} for l in lines}}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py from vo/data/vo.json */\nwindow.NS_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")

    caps = []
    for li, l in enumerate(lines):
        spec = BY[l["id"]]
        who = spec.get("who", "narrator")
        kw = {norm(k): v for k, v in spec.get("kw", {}).items()}
        EMPH.clear(); EMPH.update(kw)
        ps = phrases(l["words"])
        for pi, p in enumerate(ps):
            t0 = p[0]["start"] - 0.05
            if pi + 1 < len(ps):
                t1 = ps[pi + 1][0]["start"] - 0.05
            else:
                nxt = lines[li + 1] if li + 1 < len(lines) else None
                t1 = min(p[-1]["end"] + 0.55, (nxt["start"] - 0.12) if nxt else DUR)
            base = "a" if who == "voice" else "w"
            caps.append({"t0": round(t0, 3), "t1": round(max(t1, p[-1]["end"] + 0.05), 3), "who": who,
                         "words": [(w["w"], kw.get(norm(w["w"]), base)) for w in p]})
    for a, b in zip(caps, caps[1:]):
        if a["t1"] > b["t0"] - 0.02:
            a["t1"] = round(b["t0"] - 0.02, 3)

    divs, tl = [], []
    for k, c in enumerate(caps):
        spans = " ".join(f'<span style="color:{COL[col]}">{w.upper()}</span>' for w, col in c["words"])
        tag = ""
        if c["who"] in TAGS:
            lab, tc = TAGS[c["who"]]
            tag = f'<div class="tag" style="color:{tc}">{lab}</div>'
        divs.append(f'    <div class="clip cap" id="cap{k}" data-start="{c["t0"]:.3f}" data-duration="{c["t1"] - c["t0"]:.3f}"><div class="in" id="in{k}">{tag}<div class="line">{spans}</div></div></div>')
        tl.append(f'tl.fromTo("#in{k}", {{ opacity: 0, y: 8 }}, {{ opacity: 1, y: 0, duration: 0.08, ease: "power1.out" }}, {c["t0"]:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "NSOswald"; src: url("assets/fonts/Oswald_wght_.ttf"); font-weight: 200 700; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* measured on the source (720x1280 -> x1.5): one 1-3 word CAPS phrase, Oswald Bold ~51 px (76 px at 1080), centred at
       73 % of the height, white with a soft dark shadow, keywords yellow/red; a small coloured speaker tag above it */
    #root .cap {{ position: absolute; left: 0; right: 0; top: {CAP_Y}px; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .in {{ display: flex; flex-direction: column; align-items: center; }}
    #root .line {{ white-space: nowrap; font: 700 {CAP_PX}px/1.05 "NSOswald", "Oswald", sans-serif; letter-spacing: 0.5px;
      text-shadow: 0 4px 0 rgba(0,0,0,0.35), 0 3px 14px rgba(0,0,0,0.75), 0 0 2px rgba(0,0,0,0.6); }}
    #root .tag {{ font: 600 27px/1 "NSOswald", "Oswald", sans-serif; letter-spacing: 2.5px; margin-bottom: 8px;
      text-shadow: 0 2px 8px rgba(0,0,0,0.8); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)

    world_html = f"""<template>
  <style>
    @font-face {{ font-family: "NSOswald"; src: url("assets/fonts/Oswald_wght_.ttf"); font-weight: 200 700; }}
    @font-face {{ font-family: "NSInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    @font-face {{ font-family: "NSCaveat"; src: url("assets/fonts/Caveat_wght_.ttf"); font-weight: 400 700; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #05070b; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.NS_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "");
      const V = {{
        duration: VOD.duration,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
        we(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          return hits[Math.min(k || 0, hits.length - 1)][2];
        }},
      }};
      const K = window.NS.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.NS_FILM(K, V);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        film.draw(t);
      }}
      window.__ns = {{ K, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)

    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/ns-kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #05070b; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(caps):
            f.write(f"{k + 1}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{' '.join(w for w, _ in c['words'])}\n\n")
    nw = sum(len(c["words"]) for c in caps)
    print(f"{NAME}: {DUR} s · {len(caps)} caption phrases · {nw} words · {nw / DUR * 60:.1f} WPM")
    for c in caps:
        print(f"  {c['t0']:6.2f}-{c['t1']:6.2f} {c['who'][:5]:5s} {' '.join(w.upper() if col == 'w' else f'[{w.upper()}:{col}]' for w, col in c['words'])}")


if __name__ == "__main__":
    main()
