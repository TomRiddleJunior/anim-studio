"""Build a dark-parable project from its voice-over (after tts.py has written vo/data/vo.json + vo/audio/vo.wav):
  assets/lib/vo-data.js        word times for the film (window.DP_VO)
  compositions/captions.html   the source's caption system: ONE word at a time, centred at 46 % of the height, white bold
                               sans, fading in from grey (0.16 s) and held until the next word (max 1.6 s)
  compositions/world.html      the canvas host that runs assets/lib/film.js on the timeline clock
  index.html                   1080 x 1920 root: world + captions + the mix
  out/<name>.srt               every spoken word (one cue per phrase) beside the render, so QA counts WPM
  score/timing.json            {dur, T: shot starts} for the sound design and QA tools (read from film.js by node-free regex)

usage: python -I tools/build.py [--nomix]
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
CAP_Y = 885      # source: word centre at 46 % of the height (590/1280) -> 885 on 1920
CAP_PX = 44      # source: ~29 px bold on 720 wide -> 44 px on 1080
HOLD_MAX = 1.6


def main():
    lines = VO["lines"]
    vo_js = {"duration": DUR, "lines": {l["id"]: {"start": l["start"], "end": l["end"], "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]} for l in lines}}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8").write(
        "/* generated by tools/build.py from vo/data/vo.json */\nwindow.DP_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")

    # ---- one word at a time
    words = [w for l in lines for w in l["words"]]
    caps = []
    for i, w in enumerate(words):
        t0 = w["start"] - 0.03
        nxt = words[i + 1]["start"] - 0.03 if i + 1 < len(words) else DUR - 0.05
        t1 = min(nxt, max(w["end"] + 0.25, t0 + 0.2) + HOLD_MAX) if i + 1 < len(words) else min(DUR - 0.05, w["end"] + 1.4)
        caps.append({"t0": round(max(0.0, t0), 3), "t1": round(t1, 3), "w": w["w"]})
    divs, tl = [], []
    for k, c in enumerate(caps):
        txt = c["w"].replace("&", "&amp;").replace("<", "&lt;")
        divs.append(f'    <div class="clip cap" id="c{k}" data-start="{c["t0"]:.3f}" data-duration="{c["t1"] - c["t0"]:.3f}"><div class="wd" id="w{k}">{txt}</div></div>')
        tl.append(f'tl.fromTo("#w{k}", {{ opacity: 0.32 }}, {{ opacity: 1, duration: 0.16, ease: "power1.out" }}, {c["t0"]:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "DPInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* measured on the source (720x1280 -> x1.5): one word, centred, at 46 % of the height, bold grotesk ~29 px,
       white with a soft dark shadow; each word fades in from grey and is held until the next */
    #root .cap {{ position: absolute; left: 0; right: 0; top: {CAP_Y}px; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .wd {{ display: inline-block; white-space: nowrap; font: 700 {CAP_PX}px/1.2 "DPInter", Arial, sans-serif; letter-spacing: -0.3px; color: #f3f1ec;
      text-shadow: 0 2px 8px rgba(0,0,0,0.85), 0 0 2px rgba(0,0,0,0.9); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)

    world_html = f"""<template>
  <style>
    @font-face {{ font-family: "DPInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    @font-face {{ font-family: "DPMono"; src: url("assets/fonts/RobotoMono_wght_.ttf"); font-weight: 100 700; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #0e0e0f; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.DP_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "").replace(/'/g, "");
      const V = {{
        duration: VOD.duration,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
        we(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][2];
        }},
      }};
      const K = window.DP.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.DP_FILM(K, V);
      K.play(film.shots);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        K.render(t);
      }}
      window.__dp = {{ K, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)

    mix = "" if "--nomix" in sys.argv else f'\n      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>'
    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #0e0e0f; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>{mix}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    # ---- SRT (phrases of <= 7 words cut at punctuation) beside the render
    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    cues = []
    for l in lines:
        cur = []
        for w in l["words"]:
            cur.append(w)
            if re.search(r"[,.?!;:]$", w["w"]) or len(cur) >= 7:
                cues.append(cur); cur = []
        if cur:
            cues.append(cur)
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(cues):
            f.write(f"{k + 1}\n{ts(c[0]['start'])} --> {ts(c[-1]['end'] + 0.1)}\n{' '.join(w['w'] for w in c)}\n\n")
    nw = sum(len(c) for c in cues)
    os.makedirs(os.path.join(ROOT, "score"), exist_ok=True)
    json.dump({"dur": DUR, "words": nw, "first_word": lines[0]["start"]}, open(os.path.join(ROOT, "score", "timing.json"), "w"), indent=1)
    print(f"{NAME}: {DUR} s · {len(caps)} one-word captions · {nw} SRT words · {nw / DUR * 60:.1f} WPM")


if __name__ == "__main__":
    main()
