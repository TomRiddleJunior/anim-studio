"""Build a riddle-cutaway project from its voice-over (after tts.py wrote vo/data/vo.json + vo/audio/vo.wav):
  assets/lib/vo-data.js        word times for the film (window.RC_VO)
  compositions/captions.html   the source's caption system: short PARAPHRASE pills (not word-by-word): dark navy rounded
                               pill, white slab-serif text, top pill centred at 19 % (y 369), bottom pill at 78 % (y 1500;
                               the source sits at 85 %, we keep it out of the bottom 20 %); one pill at a time; pop-in 0.18 s
  compositions/world.html      canvas host running assets/lib/film.js on the timeline clock
  index.html                   1080 x 1920 root: world + captions + the mix
  out/<name>.srt               every spoken word (phrases) beside the render, so QA counts WPM
  score/timing.json            {dur, words, first_word, pills}
usage: python -I tools/build.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
LN = {l["id"]: l for l in VO["lines"]}
TOP_Y, BOT_Y = 369, 1500
PX = 50


def L(i):
    return LN[i]["start"]


def Le(i):
    return LN[i]["end"]


def wd(i, word, k=0):
    n = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
    hits = [x for x in LN[i]["words"] if n(x["w"]).startswith(n(word))]
    if not hits:
        raise SystemExit(f"no word {i}:{word}")
    return hits[min(k, len(hits) - 1)]["start"]


# (text, t0, t1, position, style)   style: "n" normal, "big" the reveal, "amber" amber text, "small" closing tag
def pills():
    cd0 = Le("r10") - 0.25
    return [
        ("Twins, Room 4", 0.12, L("r02") - 0.12, "top", "n"),
        ("Ivy first, at 1:55", wd("r02", "ivy") - 0.1, wd("r02", "twenty") - 0.15, "top", "n"),
        ("June, 25 minutes later", wd("r02", "twenty") - 0.15, L("r03") - 0.12, "top", "n"),
        ("Ivy is the big sister", L("r03") - 0.1, L("r04") - 0.3, "top", "n"),
        ("Every time, checked twice", wd("r04", "checks") - 0.3, L("r05") - 0.3, "bottom", "n"),
        ("Then she reads them back", L("r05") - 0.2, L("r06") - 0.15, "bottom", "n"),
        ("On paper, June came first", L("r07") - 0.1, wd("r07", "so") - 0.12, "top", "n"),
        ("The older twin goes second", wd("r07", "so") - 0.1, L("r08") - 0.2, "top", "n"),
        ("No typo", wd("r08", "no") - 0.1, wd("r08", "same") - 0.15, "top", "n"),
        ("Same clock on the wall", wd("r08", "same") - 0.15, L("r09") - 0.2, "top", "n"),
        ("How was the younger twin born first?", L("r09") - 0.1, L("r10") - 0.2, "bottom", "n"),
        ("The answer was on the wall", L("r12") - 0.1, L("r13") - 0.12, "top", "n"),
        ("The clocks went back", wd("r13", "the", 1) - 0.1, L("r14") - 0.12, "top", "big"),
        ("One hour, twice", wd("r14", "five") - 0.15, L("r15") - 0.1, "top", "small"),
        ("June: 1:20, the second time", L("r15") - 0.1, L("r16") - 0.12, "top", "n"),
        ("25 min younger, 35 min older on paper", L("r16") - 0.1, L("r17") - 0.3, "top", "n"),
        ("Ivy is older. June has the paperwork.", L("r18") - 0.1, L("r19") - 0.22, "top", "n"),
        ("Did you get it right?", L("r19") - 0.15, DUR - 0.47, "top", "amber"),
        ("Follow for more", wd("r19", "follow") - 0.2, DUR - 0.47, "bottom", "n"),
        ("Twins, Room 4", DUR - 0.45, DUR, "top", "n"),
    ], cd0


def main():
    vo_js = {"duration": DUR, "lines": {l["id"]: {"start": l["start"], "end": l["end"], "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]} for l in VO["lines"]}}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8").write(
        "/* generated by tools/build.py from vo/data/vo.json */\nwindow.RC_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")
    ps, cd0 = pills()
    divs, tl = [], []
    for k, (txt, t0, t1, pos, sty) in enumerate(ps):
        t0, t1 = round(max(0, t0), 3), round(min(DUR, t1), 3)
        y = TOP_Y if pos == "top" else BOT_Y
        size = {"big": 66, "small": 40}.get(sty, PX)
        col = "#e8a53a" if sty == "amber" else "#fbf8f1"
        divs.append(f'    <div class="clip pw" id="p{k}" data-start="{t0:.3f}" data-duration="{t1 - t0:.3f}" style="top: {y}px"><div class="pill" id="pi{k}" style="font-size: {size}px; color: {col}">{txt}</div></div>')
        if t0 > 0.2:
            tl.append(f'tl.fromTo("#pi{k}", {{ scale: 0.82, opacity: 0 }}, {{ scale: 1, opacity: 1, duration: 0.18, ease: "back.out(2.2)" }}, {t0:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "RSlab"; src: url("assets/fonts/RobotoSlab_wght_.ttf"); font-weight: 700; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* measured on the source (720x1280 -> x1.5): a navy rounded pill (#1f2633, radius ~22 % of the height), white slab
       serif ~33 px (-> 50 px), padding ~0.55 em; one pill at a time; top pill under the floor counter, bottom pill low */
    #root .pw {{ position: absolute; left: 0; right: 0; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .pill {{ display: inline-block; white-space: nowrap; font-family: "RSlab", serif; font-weight: 700; line-height: 1.0;
      padding: 0.26em 0.55em 0.3em; border-radius: 0.34em; background: #1f2633; box-shadow: 0 3px 0 rgba(0,0,0,0.18); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)

    world_html = f"""<template>
  <style>
    @font-face {{ font-family: "RSlab"; src: url("assets/fonts/RobotoSlab_wght_.ttf"); font-weight: 700; }}
    @font-face {{ font-family: "RSlabR"; src: url("assets/fonts/RobotoSlab_wght_.ttf"); font-weight: 400; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #2a3350; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.RC_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
      const V = {{
        duration: VOD.duration,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
      }};
      const K = window.RC.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.RC_FILM(K, V);
      K.play(film.shots);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        K.render(t);
      }}
      window.__rc = {{ K, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)
    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/kit.js"></script>
    <script src="assets/lib/kit-ext.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #2a3350; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    cues = []
    for l in VO["lines"]:
        cur = []
        for w in l["words"]:
            cur.append(w)
            if re.search(r"[,.?!;:]$", w["w"]) or len(cur) >= 8:
                cues.append(cur); cur = []
        if cur:
            cues.append(cur)
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(cues):
            f.write(f"{k + 1}\n{ts(c[0]['start'])} --> {ts(c[-1]['end'] + 0.1)}\n{' '.join(w['w'] for w in c)}\n\n")
    nw = sum(len(c) for c in cues)
    os.makedirs(os.path.join(ROOT, "score"), exist_ok=True)
    json.dump({"dur": DUR, "words": nw, "first_word": VO["lines"][0]["start"], "countdown_start": round(cd0, 3),
               "pills": [[p[0], round(p[1], 3), round(p[2], 3), p[3]] for p in ps]}, open(os.path.join(ROOT, "score", "timing.json"), "w"), indent=1)
    print(f"{NAME}: {DUR} s · {len(ps)} pills · {nw} SRT words · {nw / DUR * 60:.1f} WPM · countdown from {cd0:.2f}")


if __name__ == "__main__":
    main()
