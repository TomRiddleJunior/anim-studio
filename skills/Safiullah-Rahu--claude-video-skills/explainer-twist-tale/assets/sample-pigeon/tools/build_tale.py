    for k in range(6):
        cue(wt("l05", "forty") + k * 0.17, "tick", 0.14, 0.9)
    for wd, k in (("three", 0), ("them", 0), ("nose", 0)):
        cue(wt("l06", wd), "pop", 0.3, 1.0)
    cue(wt("l06", "pelican"), "whoosh", 0.24, 0.9)
    cue(wt("l07", "lens"), "shutter", 0.28)
    cue(wt("l07", "showed"), "sparkle", 0.2)
    cue(wt("l07", "drifted"), "slide", 0.3)
    for k in range(2):
        cue(wt("l07", "pecking") + k * 0.1, "click", 0.26, 1.1)
    cue(wt("l07", "back"), "whoosh", 0.3, 0.8)
    cue(wt("l08", "vote"), "blip_up", 0.26)
    cue(wt("l08", "wrong"), "error", 0.22)
    cue(wt("l08", "outvoted"), "pop", 0.3, 1.1)
    cue(wt("l08", "outvoted") + 0.15, "blip_down", 0.22)
