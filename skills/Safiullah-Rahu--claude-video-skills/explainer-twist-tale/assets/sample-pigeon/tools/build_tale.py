    for k in range(4):
        cue(wt("l04", "grain") + k * 0.05, "blip", 0.12, 1.3 + 0.1 * k)
    cue(wt("l04", "food"), "pop", 0.22, 1.2)
    t = wt("l05", "ten") - 0.1
