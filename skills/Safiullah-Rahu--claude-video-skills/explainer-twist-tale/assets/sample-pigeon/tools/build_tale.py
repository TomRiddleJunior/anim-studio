"""Twist-tale short — wires the narration to the HyperFrames project.

Writes: assets/lib/tale-vo.js (word times), compositions/world.html (the three.js shot player for
assets/lib/tale-shots.js), compositions/captions.html (1–2-word caption chunks, one clip each), index.html (1080 x 1920),
score/ (sound.json, cues, voice) for the explainer engine's sound.py.

usage: python -I tools/build_tale.py
"""
import json
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
W, H = 1080, 1920

# words that light up in the caption colour: numbers and the nouns the story turns on
HL = {"pigeons", "pigeon", "bomb", "worked", "1940", "birds", "missile", "target", "grain", "pelican", "lens", "vote",
      "outvoted", "eccentric", "impractical", "perfectly", "committee", "sank", "crazy", "dropped", "navy", "1948", "1953",
      "2024", "prize", "ig", "nobel", "peace", "problem", "seriously"}
# word pairs shown as one caption chunk (the story's names), if they fit in 13 characters
PAIRS = {("glide", "bomb"), ("ig", "nobel"), ("peace", "prize"), ("live", "pigeon"), ("real", "pigeon"), ("off", "center"),
         ("pigeon", "bomb")}
# spoken runs shown as one caption chunk with their written form (always highlighted)
MERGE = [(("world", "war", "two"), "World War II"), (("b", "f", "skinner"), "B.F. Skinner"), (("ten", "thousand"), "10,000"),
         (("fortyfive", "minutes"), "45 minutes"), (("twentyfive", "thousand", "dollars"), "$25,000")]
GLUE = {"a", "an", "the", "to", "of", "in", "on", "his", "it", "its", "and", "was", "he", "for", "with", "so", "just", "at",
        "their", "your", "every", "is", "it's", "they're", "this", "that", "when", "where", "then", "more", "less", "be"}


def norm(s):
    return re.sub(r"[^a-z0-9']", "", s.lower())


def merged(ws):
    out, i = [], 0
    while i < len(ws):
        for seq, disp in MERGE:
            n = len(seq)
            if tuple(norm(x["w"]).strip("'") for x in ws[i:i + n]) == seq:
                out.append({"w": disp, "start": ws[i]["start"], "end": ws[i + n - 1]["end"], "hl": True})
                i += n
                break
        else:
            out.append(ws[i])
            i += 1
    return out


def chunks():
    out = []
    for line in VO["lines"]:
        ws = merged(line["words"])
        i = 0
        while i < len(ws):
            cur = [ws[i]]
            pair = i + 1 < len(ws) and (norm(ws[i]["w"]), norm(ws[i + 1]["w"]).strip("'")) in PAIRS
            nextpair = i + 2 < len(ws) and (norm(ws[i + 1]["w"]), norm(ws[i + 2]["w"]).strip("'")) in PAIRS
            if ((norm(ws[i]["w"]) in GLUE and not nextpair) or pair) and i + 1 < len(ws) and not re.search(r"[,.!?:]$", ws[i]["w"]) \
                    and len(ws[i]["w"]) + len(ws[i + 1]["w"]) <= 13:
                cur.append(ws[i + 1])
                i += 1
            i += 1
            out.append(cur)
    res = []
    for k, c in enumerate(out):
        t0 = c[0]["start"]
        nxt = out[k + 1][0]["start"] if k + 1 < len(out) else DUR
        t1 = min(nxt, c[-1]["end"] + 0.45)
        words = " ".join(f'<span class="hl">{x["w"]}</span>' if x.get("hl") or norm(x["w"]).strip("'") in HL else x["w"] for x in c)
        res.append(dict(t0=round(t0, 3), t1=round(max(t1, t0 + 0.12), 3), html=words))
    return res


def main():
    lib = os.path.join(ROOT, "assets", "lib")
    words = {l["id"]: [[x["w"], round(x["start"], 3), round(x["end"], 3)] for x in l["words"]] for l in VO["lines"]}
    open(os.path.join(lib, "tale-vo.js"), "w", encoding="utf-8").write(
        "/* generated by tools/build_tale.py from vo/data/vo.json */\nwindow.TALE_VO = " + json.dumps({"dur": DUR, "lines": words}) + ";\n")

    comp = os.path.join(ROOT, "compositions")
    open(os.path.join(comp, "world.html"), "w", encoding="utf-8").write(f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #1d1712; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR}, DIS = 0.1;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "");
      const V = {{
        w(line, word, k) {{
          const hits = window.TALE_VO.lines[line].filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + line + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
      }};
      const K = window.TALE.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H}, look: {{ sat: 1.14 }} }});
      const film = window.TALE_FILM(K, V);
      const SH = film.shots;
      const ease = (u) => -(Math.cos(Math.PI * u) - 1) / 2;
      const lerp3 = (a, b, u) => [a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u];
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        let i = 0;
        while (i < SH.length - 1 && t >= SH[i + 1].t0) i++;
        // a 3-frame dissolve out of the previous shot (the format's cuts are 1–3-frame dissolves), unless s.cut
        const k = (t - SH[i].t0) / DIS;
        if (i > 0 && !SH[i].cut && k < 1) shot(i - 1, SH[i].t0 - 1 / 30, {{ toPrev: true }});
        shot(i, t, {{ mix: i > 0 && !SH[i].cut && k < 1 ? 1 - k : 0 }});
      }}
      function shot(i, t, opt) {{
        const s = SH[i], t1 = i < SH.length - 1 ? SH[i + 1].t0 : DUR;
        const u = Math.min(1, Math.max(0, (t - s.t0) / (t1 - s.t0)));
        const e = (s.ease || ease)(u);
        if (film.reset[s.set]) film.reset[s.set]();
        if (s.fn) s.fn(t, u);
        K.render({{ set: s.set, also: s.also, cam: lerp3(s.cam[0], s.cam[1], e), look: lerp3(s.look[0], s.look[1], e), fov: s.fov, light: s.light, roll: s.roll }}, opt);
      }}
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
""")

    ch = chunks()
    els = "\n    ".join(f'<div class="clip cap" id="cap{k}" data-start="{c["t0"]}" data-duration="{round(c["t1"] - c["t0"], 3)}"><span class="cw" id="cw{k}">{c["html"]}</span></div>'
                       for k, c in enumerate(ch))
    pops = "\n      ".join(f'tl.fromTo("#cw{k}", {{ scale: 0.82, opacity: 0.4 }}, {{ scale: 1, opacity: 1, duration: 0.09, ease: "back.out(2.6)" }}, {c["t0"]});' for k, c in enumerate(ch))
    open(os.path.join(comp, "captions.html"), "w", encoding="utf-8").write(f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    #root .cap {{ position: absolute; left: 60px; right: 60px; top: 1300px; height: 160px; display: flex; align-items: center; justify-content: center; }}
    #root .cw {{ display: inline-block; font: 700 104px/1.05 "Fredoka", sans-serif; color: #ffffff; text-align: center; white-space: nowrap;
      -webkit-text-stroke: 18px #22202b; paint-order: stroke fill; text-shadow: 0 8px 0 rgba(20, 16, 24, 0.35); letter-spacing: 0.01em; }}
    #root .hl {{ color: #ffd84d; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
    {els}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {pops}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
""")

    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/three.global.js"></script>
    <script src="assets/lib/tale-kit.js"></script>
    <script src="assets/lib/tale-vo.js"></script>
    <script src="assets/lib/tale-shots.js"></script>
    <style>
      @font-face {{ font-family: "Fredoka"; src: url("assets/fonts/Fredoka_wdth-wght_.ttf") format("truetype"); font-weight: 300 700; font-display: block; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #1d1712; }}
      /* families used inside scene templates, named here so the compiler embeds them */
      .font-fredoka {{ font-family: "Fredoka", sans-serif; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
""")

    # ---- sound project: voice + quiet playful bed + effects on the story's actions
    sd = os.path.join(ROOT, "score")
    os.makedirs(os.path.join(sd, "data"), exist_ok=True)
    os.makedirs(os.path.join(sd, "audio"), exist_ok=True)
    shutil.copy2(os.path.join(ROOT, "vo", "data", "vo.json"), os.path.join(sd, "data", "vo.json"))
    shutil.copy2(os.path.join(ROOT, "vo", "audio", "vo.wav"), os.path.join(sd, "audio", "vo.wav"))
    L = {l["id"]: l for l in VO["lines"]}

    def wt(line, word, k=0):
        hits = [x for x in L[line]["words"] if norm(x["w"]).startswith(norm(word))]
        return hits[min(k, len(hits) - 1)]["start"]
    cues = []

    def cue(t, kind, gain=0.5, pitch=1.0):
        cues.append({"t": round(t, 3), "type": kind, "gain": gain, "pitch": pitch})
    for t in [wt("l02", "you"), wt("l04", "so"), wt("l06", "then"), wt("l07", "steered"), wt("l09", "the"), wt("l10", "then"),
              wt("l12", "only"), wt("l13", "the", 1), wt("l14", "then"), wt("l15", "nobody")]:
        cue(t - 0.05, "swoosh", 0.26)
    cue(wt("l01", "pigeons"), "blip_up", 0.22, 1.1)
    cue(wt("l01", "bomb"), "woosh_low", 0.3)
    for k in range(3):
        cue(wt("l01", "tests") + k * 0.12, "click", 0.22, 1.1)
