    cue(wt("l12", "skinner"), "type", 0.5)
    cue(wt("l12", "crazy"), "boing", 0.22)
    cue(wt("l13", "dropped"), "drop", 0.34)
    cue(wt("l13", "dropped") + 0.25, "thud", 0.32, 1.1)
