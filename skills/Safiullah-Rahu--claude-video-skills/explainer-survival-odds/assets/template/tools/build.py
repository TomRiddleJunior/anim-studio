"""Build step for a Survival Odds demo/episode, data-driven from vo/script.json (the full episode's build is in
assets/sample/tools/build.py). Reads vo/script.json + vo/data/vo.json (Kokoro word times) and writes
  assets/lib/film-vo.js   window.FILM_VO = {dur, lines, T:{shot boundaries}, odds:[[t, value | null]]}
  compositions/hud.html   the odds ring (tools/odds_ring.py), the HUD clock, captions, the two end cards
  out/<key>.srt, index.html, score/timing.json (shot clock, captions, sound cues incl. the ring's)
script.json: "start_odds", "home_chip", "series", "day", "clock"; per line "shot" (a key in film.js; the shot starts
0.3 s before the line, the first at 0), optional "odds": {"at": word, "delta": ±n, "label"}, optional "glitch": word.
usage: python -I tools/build.py
"""
import html
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from odds_ring import OddsRing  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEY = os.path.basename(ROOT)
S = json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
LINES = {l["id"]: l for l in VO["lines"]}
COL = {"w": "#ffffff", "r": "#ff5a45", "g": "#46d483", "y": "#f7b733"}


def norm(s):
    return re.sub(r"[^a-z0-9']", "", s.lower())


def w(i, word, k=0):
    hits = [x for x in LINES[i]["words"] if norm(x["w"]) == norm(word)] or [x for x in LINES[i]["words"] if norm(x["w"]).startswith(norm(word))]
    if not hits:
        raise KeyError(f"{i}:{word}")
    return hits[min(k, len(hits) - 1)]["start"]


# shot clock: each line's "shot" starts 0.3 s before the line (the first at 0); end cards after the last line
T = {}
for n, l in enumerate(S["lines"]):
    if l.get("shot") and l["shot"] not in T:
        T[l["shot"]] = 0.0 if n == 0 else round(LINES[l["id"]]["start"] - 0.3, 3)
last = S["lines"][-1]["id"]
T["Z1"] = round(LINES[last]["end"] + 0.4, 3)
T["Z2"] = round(T["Z1"] + 2.6, 3)
first_shot = S["lines"][0]["shot"]

# the odds ring
ring = OddsRing(start=S.get("start_odds", 71))
nxt = [l for l in S["lines"] if l.get("shot") and l["shot"] != first_shot]
ring.chip(S.get("home_chip", "YOU, AT HOME: 4%"), 0.0, (T[nxt[0]["shot"]] - 0.1) if nxt else 5.0, "r")
for l in S["lines"]:
    if l.get("odds"):
        ring.recalc(w(l["id"], l["odds"]["at"]), l["odds"]["delta"], l["odds"]["label"])
    if l.get("glitch"):
        ring.glitch(w(l["id"], l["glitch"]))
r_els, r_tl, r_cues = ring.build()

fv = {"dur": DUR, "fps": 30, "T": T, "odds": [[round(t, 3), v] for t, v in ring.track()],
      "lines": {l["id"]: {"t0": l["start"], "t1": l["end"], "words": [[x["w"], x["start"], x["end"]] for x in l["words"]]} for l in VO["lines"]}}
open(os.path.join(ROOT, "assets", "lib", "film-vo.js"), "w", encoding="utf-8").write("/* generated by tools/build.py */\nwindow.FILM_VO = " + json.dumps(fv, separators=(",", ":")) + ";\n")

# captions
caps = []
for l in S["lines"]:
    words, k = LINES[l["id"]]["words"], 0
    for text, col in l["caps"]:
        n = len(text.replace("|", " ").split())
        chunk = words[k:k + n]
        assert len(chunk) == n, (l["id"], text)
        caps.append({"lid": l["id"], "text": text, "col": col, "t0": chunk[0]["start"], "t1": chunk[-1]["end"]})
        k += n
    assert k == len(words), (l["id"], k, len(words))
for i, c in enumerate(caps):
    nx = caps[i + 1]["t0"] if i + 1 < len(caps) else DUR
    c["on"], c["off"] = round(max(0.0, c["t0"] - 0.06), 3), round(min(nx - 0.04, c["t1"] + 0.7), 3)

els, tl, cues = list(r_els), list(r_tl), list(r_cues)


def clip(eid, t0, t1, inner, cls="", style=""):
    els.append(f'<div class="clip {cls}" id="{eid}" data-start="{t0:.3f}" data-duration="{max(0.05, t1 - t0):.3f}" style="{style}">{inner}</div>')


# the HUD clock from the second shot to the last line's shot
if len(nxt) > 0 and S.get("clock"):
    H0, H1 = T[nxt[0]["shot"]] + 0.25, T[S["lines"][-1]["shot"]]
    clip("hudbox", H0, H1, f'<div class="in hud"><div class="day"><span class="dot"></span>DAY {S.get("day", 1)}</div><div class="time"></div><div class="sub">NIGHT · STORM</div></div>')
    clip("tm0", H0, H1, f'<div class="in tm">{html.escape(S["clock"])}</div>', "tmw")
    for e in ("hudbox", "tm0"):
        tl.append(f'tl.fromTo("#{e} > .in", {{opacity: 0}}, {{opacity: 1, duration: 0.3}}, {H0:.3f});')
        tl.append(f'tl.to("#{e} > .in", {{opacity: 0, duration: 0.25}}, {H1 - 0.25:.3f});')
# end cards
E1 = '<div class="in end1"><div class="e1a">WHAT DID SHE</div><div class="e1b">FORGET?</div><div class="pill w">TELL ME IN THE COMMENTS <span>»</span></div></div>'
clip("end1", T["Z1"], T["Z2"], E1, "", "position:absolute;left:0;right:0;top:720px;")
tl.append(f'tl.set("#end1 > .in", {{opacity: 1}}, {T["Z1"]:.3f});')
tl.append(f'tl.fromTo("#end1 .e1a", {{opacity: 0, y: 30}}, {{opacity: 1, y: 0, duration: 0.3, ease: "power3.out"}}, {T["Z1"]:.3f});')
tl.append(f'tl.fromTo("#end1 .e1b", {{opacity: 0, scale: 1.25}}, {{opacity: 1, scale: 1, duration: 0.3, ease: "power3.out"}}, {T["Z1"] + 0.18:.3f});')
tl.append(f'tl.fromTo("#end1 .pill", {{opacity: 0, y: 16}}, {{opacity: 1, y: 0, duration: 0.3, ease: "power2.out"}}, {T["Z1"] + 0.6:.3f});')
tl.append(f'tl.to("#end1 > .in", {{opacity: 0, duration: 0.3}}, {T["Z2"] - 0.3:.3f});')
E2 = (f'<div class="in end2"><div class="glow"></div><div class="e2s">SURVIVAL ODDS</div><div class="e2a">{html.escape(S.get("series", "THE PLACE"))}</div>'
      f'<div class="e2b">DAY {int(S.get("day", 1)) + 1}</div><div class="pill r">FOLLOW FOR DAY {int(S.get("day", 1)) + 1}</div><div class="e2h">@whitelightai</div></div>')
clip("end2", T["Z2"], DUR, E2, "", "position:absolute;left:0;right:0;top:600px;")
tl.append(f'tl.fromTo("#end2 > .in", {{opacity: 0, scale: 0.94}}, {{opacity: 1, scale: 1, duration: 0.5, ease: "power2.out"}}, {T["Z2"]:.3f});')
for i, c in enumerate(caps):
    txt = "<br>".join(html.escape(p) for p in c["text"].split("|"))
    clip(f"cp{i}", c["on"], c["off"], f'<div class="in cap" style="color:{COL[c["col"]]}">{txt}</div>', "capw")
    tl.append(f'tl.fromTo("#cp{i} > .in", {{opacity: 0, y: 10}}, {{opacity: 1, y: 0, duration: 0.12, ease: "power2.out"}}, {c["on"]:.3f});')
    tl.append(f'tl.to("#cp{i} > .in", {{opacity: 0, duration: 0.08, ease: "none"}}, {c["off"] - 0.08:.3f});')
cues += [{"t": T["Z1"], "type": "endcard"}, {"t": T["Z2"], "type": "endcard2"}, {"t": round(T["Z1"] + 0.1, 3), "type": "sting_end"}]

CSS = open(os.path.join(ROOT, "tools", "hud.css"), encoding="utf-8").read() + ring.css() + """
    #root .e2s { position: relative; font: 700 30px/1 Inter, sans-serif; color: #f7b733; letter-spacing: 0.42em; padding-left: 0.42em; margin-bottom: 16px; }
    #root .e2a { font-size: 64px; letter-spacing: 0.22em; padding-left: 0.22em; }
    #root .e2h { position: relative; margin-top: 26px; font: 600 28px/1 Inter, sans-serif; color: rgba(230,236,246,0.8); letter-spacing: 0.04em; }
"""
hud = (f'<template>\n  <style>{CSS}  </style>\n  <div id="root" data-composition-id="hud" data-width="1080" data-height="1920" data-layout-allow-overflow data-layout-allow-overlap>\n'
       + "\n".join("    " + e for e in els) + '\n  </div>\n  <script>\n    (function () {\n      const tl = gsap.timeline({ paused: true });\n'
       + "\n".join("      " + x for x in tl) + '\n      window.__timelines["hud"] = tl;\n    })();\n  </script>\n</template>\n')
open(os.path.join(ROOT, "compositions", "hud.html"), "w", encoding="utf-8").write(hud)


def ts(t):
    h, r = divmod(t, 3600)
    m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)):03d}"


os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
with open(os.path.join(ROOT, "out", KEY + ".srt"), "w", encoding="utf-8") as f:
    for i, c in enumerate(caps, 1):
        f.write(f"{i}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{c['text'].replace('|', ' ')}\n\n")
open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(open(os.path.join(ROOT, "tools", "index.tmpl.html"), encoding="utf-8").read().replace("{DUR}", str(DUR)))
json.dump({"T": T, "caps": caps, "dur": DUR, "odds": fv["odds"], "cues": sorted(cues, key=lambda c: c["t"])}, open(os.path.join(ROOT, "score", "timing.json"), "w", encoding="utf-8"), indent=1)
print(f"duration {DUR} s · {len(caps)} captions · shots {T} · odds {fv['odds']}")
