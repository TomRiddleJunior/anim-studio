"""Build the fable-storybook project from the voice-over (vo/data/vo.json, written by the engine's Kokoro tts.py):
  assets/lib/vo-data.js        window.FB_VO = {duration, lines:{id:{start,end,words:[[w,s,e]]}}, chunks:[...]} for film.js
                               chunks = the karaoke caption groups (2 lines max, <= 5 words / 30 characters, a new group
                               at every sentence end and every script line, each line <= ~16 characters)
  compositions/world.html      the canvas film (fb-kit.js + film.js), seek-exact
  index.html                   1080 x 1920, data-fps (default 60, like the source), root duration = the voice-over duration
  out/<name>.srt               every caption group (for WPM in the QA and as subtitles)

usage: python -X utf8 -I tools/build.py [--fps 60]
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
FPS = int(sys.argv[sys.argv.index("--fps") + 1]) if "--fps" in sys.argv else 60
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)


FUNC = {"a", "an", "the", "to", "for", "of", "in", "on", "by", "and", "was", "were", "has", "it", "its", "so"}


def chunks():
    out = []
    for li, l in enumerate(VO["lines"]):
        cur = []
        ws = l["words"]
        for k, w in enumerate(ws):
            cur.append(w)
            txt = " ".join(x["w"] for x in cur)
            nxt = ws[k + 1] if k + 1 < len(ws) else None
            end_sent = re.search(r"[.?!:]$", w["w"]) is not None
            too_long = nxt is not None and (len(cur) >= 6 or len(txt) + 1 + len(nxt["w"]) > 32)
            comma = re.search(r",$", w["w"]) is not None and len(cur) >= 3
            if end_sent or too_long or comma or nxt is None:
                carry = []
                if too_long and not end_sent and not comma:   # don't end a group on a function word
                    while len(cur) > 2 and cur[-1]["w"].lower() in FUNC:
                        carry.insert(0, cur.pop())
                out.append({"li": li, "words": cur})
                cur = carry
    # never leave a lone short word on its own if it can join the previous group of the same line
    fixed = []
    for c in out:
        if fixed and len(c["words"]) == 1 and fixed[-1]["li"] == c["li"] and len(fixed[-1]["words"]) <= 3 and not re.search(r"[.?!:]$", fixed[-1]["words"][-1]["w"]):
            fixed[-1]["words"] += c["words"]
        else:
            fixed.append(c)
    res = []
    for i, c in enumerate(fixed):
        ws = c["words"]
        t0 = ws[0]["start"] - 0.06
        nxt0 = fixed[i + 1]["words"][0]["start"] - 0.07 if i + 1 < len(fixed) else DUR
        t1 = min(nxt0, ws[-1]["end"] + 0.55)
        text = " ".join(w["w"] for w in ws)
        if len(text) > 16 and len(ws) > 1:     # two balanced lines
            best, bi = 1e9, 1
            for j in range(1, len(ws)):
                a = len(" ".join(w["w"] for w in ws[:j])); b = len(" ".join(w["w"] for w in ws[j:]))
                if abs(a - b) < best:
                    best, bi = abs(a - b), j
            lines = [ws[:bi], ws[bi:]]
        else:
            lines = [ws]
        res.append({"t0": round(t0, 3), "t1": round(t1, 3), "lines": [[[w["w"], w["start"], w["end"]] for w in ln] for ln in lines]})
    return res


def main():
    ch = chunks()
    vo_js = {"duration": DUR, "lines": {l["id"]: {"start": l["start"], "end": l["end"], "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]} for l in VO["lines"]}, "chunks": ch}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py from vo/data/vo.json */\nwindow.FB_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")
    world = f"""<template>
  <style>
    @font-face {{ font-family: "FBNunito"; src: url("assets/fonts/Nunito_wght_.ttf"); font-weight: 200 1000; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #1b2646; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.FB_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "");
      const V = {{
        duration: VOD.duration, chunks: VOD.chunks,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
        we(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          return hits[Math.min(k || 0, hits.length - 1)][2];
        }},
      }};
      const K = window.FB.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.FB_FILM(K, V);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        film.draw(t);
      }}
      window.__fb = {{ K, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world)
    index = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/fb-kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #1b2646; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-fps="{FPS}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index)

    def ts(t):
        m, s = divmod(max(t, 0), 60)
        return f"00:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(ch):
            f.write(f"{k + 1}\n{ts(c['t0'])} --> {ts(c['t1'])}\n" + "\n".join(" ".join(w[0] for w in ln) for ln in c["lines"]) + "\n\n")
    nw = sum(len(ln) for c in ch for ln in c["lines"])
    print(f"{NAME}: {DUR} s at {FPS} fps · {len(ch)} caption groups · {nw} words · {nw / DUR * 60:.1f} WPM")
    for c in ch:
        print(f"  {c['t0']:6.2f}-{c['t1']:6.2f}  " + " / ".join(" ".join(w[0] for w in ln) for ln in c["lines"]))


if __name__ == "__main__":
    main()
