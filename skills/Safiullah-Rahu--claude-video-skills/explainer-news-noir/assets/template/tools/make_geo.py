"""Dotted-map data for the news reel: land dots for a flat Europe map and a whole-globe dot set, with a flag on the
dots inside the story's country. Natural Earth 1:10m (public domain), read locally; nothing is downloaded.
Writes assets/lib/geo.js (window.NGEO).

usage: python -X utf8 -I tools/make_geo.py <natural-earth-dir> [Country]   (default Hungary)
"""
import json
import math
import os
import sys

import numpy as np
from matplotlib.path import Path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("NE_DIR", "")
COUNTRY = sys.argv[2] if len(sys.argv) > 2 else "Hungary"
if not NE or not os.path.exists(os.path.join(NE, "ne_10m_admin_0_countries.json")):
    sys.exit("give the Natural Earth folder (ne_10m_admin_0_countries.json) as the first argument or NE_DIR")


def rings(g):
    if g["type"] == "Polygon":
        return [g["coordinates"][0]]
    return [p[0] for p in g["coordinates"]]


def main():
    d = json.load(open(os.path.join(NE, "ne_10m_admin_0_countries.json"), encoding="utf-8"))
    land, target = [], []
    for f in d["features"]:
        for r in rings(f["geometry"]):
            a = np.array(r)
            if len(a) < 4:
                continue
            p = Path(a)
            land.append((p, a[:, 0].min(), a[:, 0].max(), a[:, 1].min(), a[:, 1].max()))
            if f["properties"]["ADMIN"] == COUNTRY:
                target.append(p)

    def inside(lon, lat, paths):
        for p in paths:
            if p.contains_point((lon, lat)):
                return True
        return False

    def on_land(lon, lat):
        for p, x0, x1, y0, y1 in land:
            if x0 <= lon <= x1 and y0 <= lat <= y1 and p.contains_point((lon, lat)):
                return True
        return False

    # flat Europe map: lon -12..42, lat 34..62, spacing 0.42 deg (lon spacing / cos(lat) for even dots)
    eu = []
    lat = 34.0
    row = 0
    while lat <= 62.0:
        step = 0.42 / math.cos(math.radians(lat))
        lon = -12.0 + (step / 2 if row % 2 else 0)
        while lon <= 42.0:
            if on_land(lon, lat):
                eu.append([round(lon, 3), round(lat, 3), 1 if inside(lon, lat, target) else 0])
            lon += step
        lat += 0.42
        row += 1
    # globe: Fibonacci sphere points (~16k), keep land
    gl = []
    n = 16000
    ga = math.pi * (3 - math.sqrt(5))
    for i in range(n):
        y = 1 - 2 * (i + 0.5) / n
        lat = math.degrees(math.asin(y))
        lon = math.degrees((i * ga) % (2 * math.pi)) - 180
        if on_land(lon, lat):
            gl.append([round(lon, 2), round(lat, 2), 1 if inside(lon, lat, target) else 0])
    out = {"country": COUNTRY, "eu": eu, "globe": gl, "budapest": [19.04, 47.50]}
    p = os.path.join(ROOT, "assets", "lib", "geo.js")
    open(p, "w", encoding="utf-8").write("// generated by tools/make_geo.py from Natural Earth 1:10m (public domain)\nwindow.NGEO = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(p, "eu dots", len(eu), "(target", sum(x[2] for x in eu), ") globe dots", len(gl), "(target", sum(x[2] for x in gl), ")", os.path.getsize(p) // 1024, "KB")


main()
