"""Build the lofi-mascot-lines project from the voice-over:
  assets/lib/vo-data.js        line times (window.LOFI_VO)
  compositions/captions.html   the source's caption system: one small centred white line per scene (Inter 500 ~30 px,
                               wrapped inside a ~430 px column, centred at 31 % of the height), soft fade in with the voice,
                               out ~0.35 s before the cut; a line with "split" shows as two parts (the source's 2-part line)
  compositions/world.html      the canvas world (lofi-kit.js + film.js), seek-exact
  index.html                   1080 x 1920, 30 fps, duration = END (22.3 s)
  out/<name>.srt               the spoken lines (for WPM in the QA)
usage: python -X utf8 -I tools/build.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
END = 22.3
BAR = 60 / 70 * 4
CUTS = [0, BAR, 2 * BAR, 3 * BAR, 4.5 * BAR, 5.5 * BAR, END]
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
SPEC = {l["id"]: l for l in json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))["lines"]}
CAP_Y = 600       # caption centre: 31 % of the height (source: 31 %)
CAP_PX = 30       # source: ~19-20 px on 720 -> 29-30 px at 1080
CAP_W = 440       # wrap column (the source breaks its first line after the 5th word)


def next_cut(t):
    return min(c for c in CUTS if c > t + 0.01)


def main():
    lines = VO["lines"]
    vo_js = {"duration": END, "lines": {l["id"]: {"start": l["start"], "end": l["end"]} for l in lines}}
    with open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py */\nwindow.LOFI_VO = " + json.dumps(vo_js) + ";\n")
    caps = []
    for l in lines:
        sp = SPEC[l["id"]].get("split")
        words = l["words"]
        if sp:
            k = next(i for i, w in enumerate(words) if w["w"] == sp) + 1
            parts = [words[:k], words[k:]]
        else:
            parts = [words]
        for j, p in enumerate(parts):
            t0 = p[0]["start"] - 0.12
            t1 = (parts[j + 1][0]["start"] - 0.12) if j + 1 < len(parts) else min(next_cut(p[0]["start"]) - 0.35, p[-1]["end"] + 1.2)
            caps.append({"t0": round(t0, 3), "t1": round(t1, 3), "text": " ".join(w["w"] for w in p)})
    divs, tl = [], []
    for k, c in enumerate(caps):
        divs.append(f'    <div class="clip cap" id="cap{k}" data-start="{c["t0"]:.3f}" data-duration="{c["t1"] - c["t0"]:.3f}"><div class="in" id="in{k}">{c["text"]}</div></div>')
        d = c["t1"] - c["t0"]
        tl.append(f'tl.fromTo("#in{k}", {{ opacity: 0 }}, {{ opacity: 1, duration: 0.28, ease: "sine.out" }}, {c["t0"]:.3f}); '
                  f'tl.to("#in{k}", {{ opacity: 0, duration: 0.22, ease: "sine.in" }}, {c["t0"] + d - 0.24:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "LFInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* measured on the source: one small white line per scene, centred at 31 % of the height, wrapped in a narrow column */
    #root .cap {{ position: absolute; left: 0; right: 0; top: {CAP_Y}px; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .in {{ width: {CAP_W}px; text-align: center; color: #f7f4ee; font: 500 {CAP_PX}px/1.32 "LFInter", "Inter", sans-serif; letter-spacing: -0.1px;
      text-shadow: 0 1px 2px rgba(0,0,0,0.45), 0 0 18px rgba(0,0,0,0.35); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)
    world_html = f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #0a0c14; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {END};
      const VOD = window.LOFI_VO;
      const V = {{ duration: DUR, L(id) {{ return VOD.lines[id]; }} }};
      const cv = document.getElementById("world-canvas"), ctx = cv.getContext("2d");
      const film = window.LOFI_FILM(V);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        film.draw(ctx, t);
      }}
      window.__lofi = {{ film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = film.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)
    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/lofi-kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #0a0c14; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{END}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{END}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{END}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{END}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(caps):
            f.write(f"{k + 1}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{c['text']}\n\n")
    nw = sum(len(c["text"].split()) for c in caps)
    print(f"{NAME}: {END} s · {len(caps)} captions · {nw} words · {nw / END * 60:.1f} WPM")
    for c in caps:
        print(f"  {c['t0']:6.2f}-{c['t1']:6.2f}  {c['text']}")


if __name__ == "__main__":
    main()
