"""Build the stickman night choice project from the voice-over (vo/data/vo.json, written by the engine's tts.py):
  assets/lib/vo-data.js       word times (window.SM_VO) for film.js
  compositions/captions.html  the format's captions: word-by-word groups of 1-2 heavy CAPS words (Montserrat 900),
                              white, keywords lime (script "kw" map), centred at CAP_Y; none on the vote card
  compositions/world.html     the canvas world (sm-kit.js + film.js), seek-exact; the HUD is drawn in the canvas
  index.html                  1080x1920, 30 fps
  out/<name>.srt              every spoken line, phrase by phrase (WPM in the QA)
usage: python -X utf8 -I tools/build.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
SPEC = json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))
BY = {l["id"]: l for l in SPEC["lines"]}
DUR = round(VO["duration"], 2)
CAP_Y = 1258          # source: 77 % (y 1480); moved up into the 9:16 safe area (key text above ~1300)
CAP_PX = 92           # source: Montserrat Black, cap height ~66 px at 1080
NO_CAPS = set(SPEC.get("no_caption_lines", ["s13", "s14", "s15", "s16"]))   # the vote card carries these words
WHITE, LIME = "#f3f3ee", "#c8f53c"
PUNCT = r"[,.?!;:…]$"


def norm(s):
    return re.sub(r"[^a-z0-9'\-]", "", s.lower())


def phrases(words):
    """1-2 word groups (<= 14 characters), a break after punctuation; a short function word rides with the next."""
    out, cur = [], []
    for k, w in enumerate(words):
        cur.append(w)
        txt = " ".join(x["w"] for x in cur)
        nxt = words[k + 1] if k + 1 < len(words) else None
        long_next = nxt is not None and len(txt) + 1 + len(nxt["w"]) > 14
        if re.search(PUNCT, w["w"]) or len(cur) >= 2 or long_next:
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    return out


def main():
    lines = VO["lines"]
    vo_js = {"duration": DUR, "lines": {l["id"]: {"start": l["start"], "end": l["end"], "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]} for l in lines}}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py from vo/data/vo.json */\nwindow.SM_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")
    caps, srt = [], []
    for li, l in enumerate(lines):
        kw = {norm(k) for k in BY[l["id"]].get("kw", {})}
        ps = phrases(l["words"])
        for pi, p in enumerate(ps):
            t0 = p[0]["start"] - 0.04
            if pi + 1 < len(ps):
                t1 = ps[pi + 1][0]["start"] - 0.04
            else:
                nxt = lines[li + 1] if li + 1 < len(lines) else None
                t1 = min(p[-1]["end"] + 0.5, (nxt["start"] - 0.08) if nxt else DUR)
            c = {"t0": round(t0, 3), "t1": round(max(t1, p[-1]["end"] + 0.05), 3), "words": [(w["w"], norm(w["w"]) in kw) for w in p]}
            srt.append(c)
            if l["id"] not in NO_CAPS:
                caps.append(c)
    for a, b in zip(caps, caps[1:]):
        if a["t1"] > b["t0"] - 0.02:
            a["t1"] = round(b["t0"] - 0.02, 3)
    divs, tl = [], []
    for k, c in enumerate(caps):
        spans = " ".join(f'<span style="color:{LIME if hot else WHITE}">{w.upper()}</span>' for w, hot in c["words"])
        cls = "line two" if len(" ".join(w for w, _ in c["words"])) > 12 else "line"
        divs.append(f'    <div class="clip cap" id="cap{k}" data-start="{c["t0"]:.3f}" data-duration="{c["t1"] - c["t0"]:.3f}"><div class="in" id="in{k}"><div class="{cls}">{spans}</div></div></div>')
        tl.append(f'tl.fromTo("#in{k}", {{ scale: 1.12, opacity: 0 }}, {{ scale: 1, opacity: 1, duration: 0.09, ease: "power2.out" }}, {c["t0"]:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "SMCap"; src: url("assets/fonts/Montserrat_wght_.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* the format: 1-2 heavy CAPS words at a time (Montserrat Black), white with lime keywords, a soft dark shadow;
       centred at y {CAP_Y} (the source sits at 77 %, under the 9:16 safe area); a 12 % pop on each group */
    #root .cap {{ position: absolute; left: 0; right: 0; top: {CAP_Y}px; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .in {{ display: flex; flex-direction: column; align-items: center; }}
    #root .line {{ white-space: nowrap; font: 900 {CAP_PX}px/1.0 "SMCap", "Montserrat", sans-serif; letter-spacing: -1px;
      text-shadow: 0 3px 0 rgba(0,0,0,0.75), 0 0 18px rgba(0,0,0,0.85), 0 0 3px rgba(0,0,0,0.9); }}
    #root .line.two {{ font-size: {CAP_PX - 10}px; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)
    world_html = f"""<template>
  <style>
    @font-face {{ font-family: "SMCond"; src: url("assets/fonts/Oswald_wght_.ttf"); font-weight: 200 700; }}
    @font-face {{ font-family: "SMMono"; src: url("assets/fonts/RobotoMono_wght_.ttf"); font-weight: 100 700; }}
    @font-face {{ font-family: "SMUI"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #05070d; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.SM_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "");
      const V = {{
        duration: VOD.duration,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
      }};
      const K = window.SM.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.SM_FILM(K, V);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        film.draw(t);
      }}
      window.__sm = {{ K, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = K.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)
    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/sm-kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #05070d; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, c in enumerate(srt):
            f.write(f"{k + 1}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{' '.join(w for w, _ in c['words'])}\n\n")
    nw = sum(len(c["words"]) for c in srt)
    print(f"{NAME}: {DUR} s · {len(caps)} on-screen groups · {nw} words · {nw / DUR * 60:.1f} WPM")


if __name__ == "__main__":
    main()
