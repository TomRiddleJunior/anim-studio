"""Build the glow-story project from the voice-over: assets/lib/vo-data.js (word times + the message waveform envelope),
compositions/captions.html (the source's caption system: one 1-4 word phrase at a time, low centre, grey with the
spoken word lit white), compositions/world.html, index.html (1080 x 1920, 30 fps) and out/<name>.srt (beside the
render, so the QA counts words per minute; the voicemail voices are in it although on screen their words are in the
bubbles).

usage: python -I tools/build.py        (after tts.py has written vo/data/vo.json + vo/audio/vo.wav)
"""
import json
import os
import re
import sys

import numpy as np
import soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = os.path.basename(ROOT)
W, H = 1080, 1920
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
SPEC = json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))
WHO = {l["id"]: l.get("who", "narrator") for l in SPEC["lines"]}
DUR = round(VO["duration"], 2)
CAP_Y = 1262          # caption centre: 65.7 % of the height (source: 66 %), inside the safe area (out of the bottom 20 %)
CAP_PX = 47           # source: 31 px on 720 wide -> 46.5 px on 1080
GREY, LIT = "#7d838e", "#f4f6fa"


def phrases(words):
    """Greedy 1-4 word phrases (<= 21 characters), always breaking after , . ? ! ; : — the source's rhythm."""
    NUM = {"one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "twenty", "thirty",
           "forty", "fifty", "sixty", "seventy", "eighty", "ninety", "hundred", "thousand", "million", "and"}
    bare = lambda x: x["w"].lower().strip(",.?!;:")
    out, cur = [], []
    for k, w in enumerate(words):
        cur.append(w)
        txt = " ".join(x["w"] for x in cur)
        nxt = words[k + 1] if k + 1 < len(words) else None
        glue = nxt is not None and bare(w) in NUM and bare(nxt) in NUM and bare(nxt) != "one" and not re.search(r"[,.?!;:]$", w["w"]) and len(cur) < 6
        if re.search(r"[,.?!;:]$", w["w"]) or ((len(cur) >= 4 or len(txt) >= 21) and not glue):
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    # a lone sentence-final word after a 3-4 word phrase borrows the previous word ("allowed / to listen.")
    for i in range(1, len(out)):
        prev = out[i - 1]
        numpair = len(prev) >= 2 and bare(prev[-1]) in NUM and bare(prev[-2]) in NUM
        if len(out[i]) == 1 and len(prev) >= 3 and not re.search(r"[,.?!;:]$", prev[-1]["w"]) and not numpair:
            out[i] = [out[i - 1].pop()] + out[i]
    # never leave a single short word dangling after a long phrase: merge it back when the result still fits
    fixed = []
    for p in out:
        if fixed and len(p) == 1 and not re.search(r"[,.?!;:]$", fixed[-1][-1]["w"]) and len(" ".join(x["w"] for x in fixed[-1] + p)) <= 24:
            fixed[-1] = fixed[-1] + p
        else:
            fixed.append(p)
    return fixed


def main():
    lines = VO["lines"]
    # ---- vo-data.js
    vo_js = {"duration": DUR, "lines": {}}
    for l in lines:
        vo_js["lines"][l["id"]] = {"start": l["start"], "end": l["end"], "who": WHO.get(l["id"], "narrator"),
                                   "words": [[w["w"], w["start"], w["end"]] for w in l["words"]]}
    # the 9-second message waveform: 0:00-0:04 near silence with one breath, then the real voice envelope of m1, then air
    v, sr = sf.read(os.path.join(ROOT, "vo", "audio", "vo.wav"), always_2d=False)
    m1 = next((l for l in lines if l["id"] == "m1"), None) or next((l for l in lines if WHO.get(l["id"], "narrator") != "narrator"), lines[-1])
    seg = v[int((m1["start"] - 0.05) * sr):int((m1["end"] + 0.1) * sr)]
    n_sp = 66
    hop = max(1, len(seg) // n_sp)
    rms = np.array([np.sqrt(np.mean(seg[i * hop:(i + 1) * hop] ** 2)) for i in range(n_sp)])
    rms = (rms / (rms.max() + 1e-9)) ** 0.8
    env = [0.02 + 0.015 * abs(np.sin(i * 1.9)) for i in range(50)]
    env[20:26] = [0.05, 0.11, 0.14, 0.12, 0.07, 0.03]  # the breath
    env += [round(float(x), 3) for x in rms] + [0.02 + 0.01 * abs(np.sin(i)) for i in range(14)]
    vo_js["env"] = {"m1": [round(float(x), 3) for x in env]}
    os.makedirs(os.path.join(ROOT, "assets", "lib"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "lib", "vo-data.js"), "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build.py from vo/data/vo.json */\nwindow.GLOW_VO = " + json.dumps(vo_js, ensure_ascii=False) + ";\n")

    # ---- captions (narrator only; the voicemail voices read as the bubbles on screen, as in the source)
    caps = []
    for li, l in enumerate(lines):
        if WHO.get(l["id"], "narrator") != "narrator":
            continue
        ps = phrases(l["words"])
        for pi, p in enumerate(ps):
            t0 = p[0]["start"] - 0.06
            if pi + 1 < len(ps):
                t1 = ps[pi + 1][0]["start"] - 0.06
            else:
                nxt = next((x for x in lines[li + 1:]), None)
                t1 = min(p[-1]["end"] + 0.42, (nxt["start"] - 0.1) if nxt else DUR)
            caps.append({"t0": round(t0, 3), "t1": round(max(t1, p[-1]["end"] + 0.05), 3), "words": p})
    for a, b in zip(caps, caps[1:]):  # no overlap
        if a["t1"] > b["t0"] - 0.02:
            a["t1"] = round(b["t0"] - 0.02, 3)
    divs, tl = [], []
    for k, c in enumerate(caps):
        spans = []
        for j, w in enumerate(c["words"]):
            sid = f"w{k}_{j}"
            spans.append(f'<span id="{sid}" class="wd">{w["w"]}</span>')
            nxt = c["words"][j + 1]["start"] if j + 1 < len(c["words"]) else None
            tl.append(f'tl.to("#{sid}", {{ color: "{LIT}", textShadow: "0 0 18px rgba(190,215,255,0.45)", duration: 0.06, ease: "none" }}, {max(c["t0"], w["start"] - 0.02):.3f});')
            if nxt is not None:
                tl.append(f'tl.to("#{sid}", {{ color: "{GREY}", textShadow: "0 0 0px rgba(0,0,0,0)", duration: 0.1, ease: "none" }}, {nxt - 0.02:.3f});')
        divs.append(f'    <div class="clip cap" id="cap{k}" data-start="{c["t0"]:.3f}" data-duration="{c["t1"] - c["t0"]:.3f}"><div class="line" id="ln{k}">{" ".join(spans)}</div></div>')
        tl.append(f'tl.fromTo("#ln{k}", {{ opacity: 0, y: 6 }}, {{ opacity: 1, y: 0, duration: 0.14, ease: "power1.out" }}, {c["t0"]:.3f}); '
                  f'tl.to("#ln{k}", {{ opacity: 0, duration: 0.12, ease: "none" }}, {c["t1"] - 0.13:.3f});')
    cap_html = f"""<template>
  <style>
    @font-face {{ font-family: "GInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; }}
    /* measured on the source (720x1280 -> x1.5): one phrase of 1-4 words, centred at 66 % of the height, a light
       geometric grotesk ~31 px, unspoken words grey, the spoken word lit white with a faint glow */
    #root .cap {{ position: absolute; left: 0; right: 0; top: {CAP_Y}px; height: 0; display: flex; justify-content: center; align-items: center; }}
    #root .line {{ display: inline-block; white-space: nowrap; font: 440 {CAP_PX}px/1.2 "GInter", "Inter", Arial, sans-serif; letter-spacing: -0.2px; color: {GREY};
      text-shadow: 0 0 0 rgba(0,0,0,0); }}
    #root .wd {{ color: {GREY}; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(divs)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      {chr(10) + "      ".join(tl)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_html)

    world_html = f"""<template>
  <style>
    @font-face {{ font-family: "GInter"; src: url("assets/fonts/Inter_opsz-wght_.ttf"); font-weight: 100 900; }}
    @font-face {{ font-family: "GPoppins"; src: url("assets/fonts/Poppins-Medium.ttf"); font-weight: 500; }}
    @font-face {{ font-family: "GPoppins"; src: url("assets/fonts/Poppins-SemiBold.ttf"); font-weight: 600; }}
    #root {{ position: absolute; inset: 0; overflow: hidden; background: #05070b; }}
    #world-canvas {{ position: absolute; left: 0; top: 0; width: {W}px; height: {H}px; }}
  </style>
  <div id="root" data-composition-id="world" data-width="{W}" data-height="{H}">
    <canvas id="world-canvas" width="{W}" height="{H}" data-layout-allow-overflow></canvas>
  </div>
  <script>
    (function () {{
      const DUR = {DUR};
      const VOD = window.GLOW_VO;
      const norm = (s) => s.toLowerCase().replace(/[^a-z0-9']/g, "");
      const V = {{
        env: VOD.env, duration: VOD.duration,
        L(id) {{ const l = VOD.lines[id]; if (!l) throw new Error("no line " + id); return l; }},
        w(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          if (!hits.length) throw new Error("no word " + id + ":" + word);
          return hits[Math.min(k || 0, hits.length - 1)][1];
        }},
        we(id, word, k) {{
          const hits = VOD.lines[id].words.filter((x) => norm(x[0]).startsWith(norm(word)));
          return hits[Math.min(k || 0, hits.length - 1)][2];
        }},
      }};
      const G = window.GLOW.create({{ canvas: document.getElementById("world-canvas"), width: {W}, height: {H} }});
      const film = window.GLOW_FILM(G, V);
      let ready = false, lastT = -1, curT = 0;
      function draw(t) {{
        curT = t;
        t = Math.round(t * 10000) / 10000;
        if (!ready || t === lastT) return;
        lastT = t;
        G.render(film.update(t));
      }}
      window.__glow = {{ G, film, draw: (t) => {{ lastT = -1; draw(t); }} }};
      window.__hf = window.__hf || {{}};
      window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.world = G.ready.then(() => {{ ready = true; lastT = -1; draw(curT); }});
      window.addEventListener("hf-seek", (e) => draw(e.detail.time));
      const tl = gsap.timeline({{ paused: true }});
      const clock = {{ t: 0 }};
      tl.to(clock, {{ t: DUR, duration: DUR, ease: "none", onUpdate: () => draw(clock.t) }}, 0);
      window.__timelines["world"] = tl;
    }})();
  </script>
</template>
"""
    open(os.path.join(ROOT, "compositions", "world.html"), "w", encoding="utf-8").write(world_html)

    # --mask: QA build for tools/frame_check.py (objects white on black, captions hidden); never render this one
    MASK = ('\n    <script>window.GLOW_MASK = true;</script>\n    <style>#captions { display: none !important; }</style>'
            if "--mask" in sys.argv else "")
    index_html = f"""<!doctype html>
<html lang="en" data-size="{W}x{H}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/lib/three.global.js"></script>
    <script src="assets/lib/glow-kit.js"></script>
    <script src="assets/lib/vo-data.js"></script>
    <script src="assets/lib/film.js"></script>{MASK}
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #05070b; }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR}" data-width="{W}" data-height="{H}">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html" data-start="0" data-duration="{DUR}" data-track-index="0" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="z-index: 1"></div>
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{DUR}" data-track-index="1" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index: 5"></div>
      <audio id="mix" class="clip" src="assets/audio/final.m4a" data-start="0" data-duration="{DUR}" data-track-index="20" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(index_html)

    # ---- SRT beside the render: every spoken line (narrator phrases + the voicemail voices)
    def ts(t):
        h, r = divmod(max(t, 0), 3600)
        m, s = divmod(r, 60)
        return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)) % 1000:03d}"
    srt = []
    for c in caps:
        srt.append((c["t0"], c["t1"], " ".join(w["w"] for w in c["words"])))
    for l in lines:
        if WHO.get(l["id"], "narrator") != "narrator":
            srt.append((l["start"] - 0.05, l["end"] + 0.2, l["text"]))
    srt.sort()
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    with open(os.path.join(ROOT, "out", NAME + ".srt"), "w", encoding="utf-8") as f:
        for k, (a, b, txt) in enumerate(srt):
            f.write(f"{k + 1}\n{ts(a)} --> {ts(b)}\n{txt}\n\n")
    nw = sum(len(x[2].split()) for x in srt)
    print(f"{NAME}: {DUR} s · {len(caps)} caption phrases · {nw} SRT words · {nw / DUR * 60:.1f} WPM")
    for c in caps:
        print(f"  {c['t0']:6.2f}-{c['t1']:6.2f}  {' '.join(w['w'] for w in c['words'])}")


if __name__ == "__main__":
    main()
