"""Sim-flight template — wires the narration (vo/data/vo.json) and film.json to the HyperFrames project.

Writes: assets/lib/sim-vo.js (word + line times), compositions/world.html (the three.js shot player for
assets/lib/sim-shots.js), compositions/captions.html (phrase captions + the format's chrome: watermark, info cards,
illustration note, tags, picture-in-picture frame), index.html (1080 x 1920), score/ (cues, voice, sound.json).

usage: python -I tools/build_sim.py            (then tools/ambience.py, engine sound.py, ffmpeg -> assets/audio/final.m4a)

film.json: {"brand": "Vectorwing", "cut_lead": 0.28,
  "chunks": {"l01": ["A jet built", "to break the sound barrier,", ...]},     # optional per line; auto-chunked otherwise
  "chrome": [{"kind": "note|card|tag|inset", "at": T, "until": T, ...}],       # T = "l02" (that line's cut) | ["l05", "this", -0.3] | "end"
  "ambience": [{"at": T, "kind": "jet|prop|afterburner|wind|crickets|high", "gain": 1}],
  "events": [{"at": T, "kind": "boom|thump|whoosh", "gain": 1}], "cues": [{"at": T, "type": "whoosh", "gain": 0.4}]}
"""
import json
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
W, H = 1080, 1920
L = {l["id"]: l for l in VO["lines"]}


def norm(s):
    return re.sub(r"[^a-z0-9']", "", s.lower())


def wt(line, word, k=0):
    hits = [x for x in L[line]["words"] if norm(x["w"]).startswith(norm(word))]
    return hits[min(k, len(hits) - 1)]["start"]


def line0(i):
    return L[i]["start"] - 0.28


FILM = json.load(open(os.path.join(ROOT, "film.json"), encoding="utf-8"))
LEAD = FILM.get("cut_lead", 0.28)


def line0(i):
    return L[i]["start"] - LEAD


def T_(spec):
    """time spec -> seconds: "l02" = that line's cut; ["l05", "this", -0.3] = word start + offset; "end"; or a number."""
    if isinstance(spec, (int, float)):
        return float(spec)
    if spec == "end":
        return DUR
    if isinstance(spec, str):
        return line0(spec)
    t = wt(spec[0], spec[1], spec[3] if len(spec) > 3 else 0)
    return t + (spec[2] if len(spec) > 2 else 0)


# ---------------------------------------------------------------- caption chunks (2-6 words, phrase breaks)
BREAK_BEFORE = {"that", "and", "but", "from", "for", "on", "at", "to", "like", "with", "so", "then", "while", "by", "into", "if", "without", "about"}


def auto_chunks(words):
    out, cur = [], []
    for x in words:
        if cur:
            prev = cur[-1]["w"]
            chars = len(" ".join(c["w"] for c in cur))
            if re.search(r"[,.!?:;]$", prev) or (norm(x["w"]) in BREAK_BEFORE and len(cur) >= 2) or chars + len(x["w"]) > 28 or len(cur) >= 6:
                out.append(cur)
                cur = []
        cur.append(x)
    if cur:
        out.append(cur)
    return [" ".join(c["w"] for c in g) for g in out]


def chunks():
    out = []
    for line in VO["lines"]:
        ws, k = line["words"], 0
        for text in FILM.get("chunks", {}).get(line["id"]) or auto_chunks(ws):
            n = len(text.split())
            seg = ws[k:k + n]
            assert len(seg) == n, (line["id"], text)
            out.append((seg[0]["start"], text))
            k += n
        assert k == len(ws), (line["id"], k, len(ws))
    res = []
    for i, (t0, text) in enumerate(out):
        nxt = out[i + 1][0] if i + 1 < len(out) else DUR
        res.append(dict(t0=round(t0, 3), t1=round(nxt, 3), text=text))
    return res


def schedule():
    out = []
    for c in FILM.get("chrome", []):
        d = dict(c)
        d["t0"], d["t1"] = T_(c["at"]), T_(c["until"])
        out.append(d)
    return out


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


