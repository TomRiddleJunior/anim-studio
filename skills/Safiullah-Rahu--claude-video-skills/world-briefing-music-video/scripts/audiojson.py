"""data/audio.json for the engine: duration, a beat grid (the score's tempo), sections (the scenes), 100 fps
envelopes and onsets. Called by tools/sound.py with its stems; run alone it builds a provisional file from the
voiceover so the picture can be previewed before the soundtrack exists.   python tools/audiojson.py
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
FPS = 100


def env(x, sr, attack=0.01, release=0.09):
    if x.ndim > 1:
        x = x.mean(axis=1)
    hop = sr // FPS
    n = len(x) // hop
    fr = x[: n * hop].reshape(n, hop)
    rms = np.sqrt((fr.astype(np.float64) ** 2).mean(axis=1) + 1e-12)
    out = np.zeros_like(rms)
    a, r = np.exp(-1 / (attack * FPS)), np.exp(-1 / (release * FPS))
    v = 0.0
    for i, s in enumerate(rms):
        k = a if s > v else r
        v = k * v + (1 - k) * s
        out[i] = v
    p = np.percentile(out, 99) or 1.0
    return np.clip(out / p, 0, 1)


def build(duration, stems, sr, bpm=96.0, t0=0.0, word_onsets=None, sfx_onsets=None, scenes=None):
    """stems: dict name -> mono/stereo float array (same length/sr). Keys used: vocal, music, sfx, mix."""
    beat = 60.0 / bpm
    beats = [round(t0 + i * beat, 4) for i in range(int((duration - t0) / beat) + 1)]
    downbeats = beats[::4]
    E = {k: env(v, sr) for k, v in stems.items()}
    n = max(len(v) for v in E.values())
    z = np.zeros(n)
    pick = lambda k: (E.get(k, z)[:n] if k in E else z)  # noqa: E731
    mix = pick("mix") if "mix" in E else np.clip(pick("vocal") + pick("music") + pick("sfx"), 0, 1)
    j = {
        "duration": round(duration, 3), "bpm": bpm, "beat_period": beat, "time_signature": 4, "key": "D major",
        "beats": beats, "downbeats": downbeats,
        "sections": [{"name": s["id"], "start": s["t0"], "end": s["t1"]} for s in (scenes or [])],
        "fps": FPS,
        "rms": np.round(mix, 3).tolist(), "low": np.round(pick("music") * 0.8, 3).tolist(), "mid": np.round(mix, 3).tolist(),
        "high": np.round(pick("sfx"), 3).tolist(), "vocal": np.round(pick("vocal"), 3).tolist(), "drums": np.round(pick("sfx"), 3).tolist(),
        "bass": np.round(pick("music") * 0.6, 3).tolist(), "other": np.round(pick("music"), 3).tolist(),
        "onsets": {"kick": [[round(b, 3), 0.5] for b in downbeats], "snare": [], "hat": [],
                   "vocal": [[round(t, 3), 1.0] for t in (word_onsets or [])]},
        "notes": "Generated by tools/audiojson.py (explainer film: vocal = narration, other = score, drums/high = sound effects).",
    }
    (ROOT / "data" / "audio.json").write_text(json.dumps(j), encoding="utf-8")
    return j


if __name__ == "__main__":
    import soundfile as sf
    vo = json.loads((ROOT / "data" / "vo.json").read_text(encoding="utf-8"))
    x, sr = sf.read(ROOT / "audio" / "vo.wav", always_2d=False)
    words = [w["start"] for l in vo["lines"] for w in l["words"]]
    build(vo["duration"], {"vocal": x, "mix": x}, sr, word_onsets=words, scenes=vo["scenes"])
    print("wrote data/audio.json (provisional, from the voiceover)")
