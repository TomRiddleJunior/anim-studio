"""Map data for the map shot: land polygons around the Dutch coast from Natural Earth 1:10m (public domain),
projected to a local plane (km east / km south of the barrier), simplified, written to assets/lib/geo.js.

usage: python -X utf8 -I tools/make_geo.py <natural-earth-dir>
       (the folder that holds ne_10m_admin_0_countries.json; nothing is downloaded)
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("NE_DIR", "")
if not NE or not os.path.exists(os.path.join(NE, "ne_10m_admin_0_countries.json")):
    sys.exit("give the Natural Earth folder (ne_10m_admin_0_countries.json) as the first argument or NE_DIR")
LON0, LAT0 = 4.164, 51.955            # the barrier (Nieuwe Waterweg near Hoek van Holland)
BOX = (1.2, 50.6, 8.2, 54.4)          # lon/lat window
KX = 111.32 * math.cos(math.radians(LAT0))
KY = 110.57


def proj(lon, lat):
    return round((lon - LON0) * KX, 2), round(-(lat - LAT0) * KY, 2)   # x east (km), z south (km)


def simplify(pts, tol):
    """Douglas-Peucker on a closed ring (list of (x, z))."""
    if len(pts) < 5:
        return pts

    def rdp(a, b):
        (x1, z1), (x2, z2) = pts[a], pts[b]
        dx, dz = x2 - x1, z2 - z1
        L = math.hypot(dx, dz) or 1e-9
        best, bi = 0, -1
        for i in range(a + 1, b):
            x0, z0 = pts[i]
            d = abs(dz * x0 - dx * z0 + x2 * z1 - z2 * x1) / L
            if d > best:
                best, bi = d, i
        if best > tol:
            return rdp(a, bi)[:-1] + rdp(bi, b)
        return [pts[a], pts[b]]

    # a closed ring: split at the point farthest from the first, simplify both halves
    x0, z0 = pts[0]
    far = max(range(len(pts)), key=lambda i: (pts[i][0] - x0) ** 2 + (pts[i][1] - z0) ** 2)
    return rdp(0, far)[:-1] + rdp(far, len(pts) - 1)


def main():
    d = json.load(open(os.path.join(NE, "ne_10m_admin_0_countries.json"), encoding="utf-8"))
    rings = []
    for f in d["features"]:
        name = f["properties"].get("ADMIN") or f["properties"].get("NAME")
        if name not in ("Netherlands", "Belgium", "Germany", "France", "United Kingdom", "Luxembourg"):
            continue
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poly in polys:
            ring = poly[0]
            lons = [p[0] for p in ring]
            lats = [p[1] for p in ring]
            if max(lons) < BOX[0] or min(lons) > BOX[2] or max(lats) < BOX[1] or min(lats) > BOX[3]:
                continue
            pts = [proj(lo, la) for lo, la in ring]
            pts = simplify(pts, 0.35)
            if len(pts) >= 4:
                rings.append({"c": name, "p": [c for xy in pts for c in xy]})
    # the shipping channel from the sea to Rotterdam (hand-placed along the Nieuwe Waterweg / Nieuwe Maas)
    chan = [(4.03, 51.995), (4.12, 51.982), (4.164, 51.955), (4.23, 51.92), (4.30, 51.905), (4.38, 51.90),
            (4.43, 51.905), (4.48, 51.912)]
    places = {"barrier": proj(4.164, 51.955), "rotterdam": proj(4.48, 51.92), "hoek": proj(4.12, 51.98),
              "storm": proj(2.4, 53.0)}
    out = {"rings": rings, "chan": [c for lo, la in chan for c in proj(lo, la)], "places": places}
    js = "// generated by tools/make_geo.py from Natural Earth 1:10m (public domain); km, x east, z south of the barrier\n"
    js += "window.GEO = " + json.dumps(out, separators=(",", ":")) + ";\n"
    p = os.path.join(ROOT, "assets", "lib", "geo.js")
    open(p, "w", encoding="utf-8").write(js)
    print(p, len(rings), "rings", sum(len(r["p"]) // 2 for r in rings), "points", os.path.getsize(p) // 1024, "KB")


main()
