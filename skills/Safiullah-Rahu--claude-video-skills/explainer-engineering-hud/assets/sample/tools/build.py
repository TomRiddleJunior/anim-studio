"""Timing build: vo/data/vo.json (Kokoro word times) -> assets/lib/timing.js (lines, words, caption phrases),
out/<KEY>.srt (display text) and the root duration in index.html.

Display substitutions turn spoken number words back into digits for the captions ("twenty twenty-three" -> "2023");
the merged token keeps the first word's start and the last word's end.
usage: python -X utf8 -I tools/build.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = json.load(open(os.path.join(ROOT, "tools", "film.json"), encoding="utf-8"))
KEY = CFG["key"]


def norm(w):
    return re.sub(r"[^a-z0-9'\-]", "", w.lower())


def substitute(words, subs):
    out, i = [], 0
    while i < len(words):
        hit = None
        for spoken, disp in subs:
            toks = spoken.lower().split()
            seg = words[i:i + len(toks)]
            if len(seg) == len(toks) and all(norm(a["w"]) == norm(b) for a, b in zip(seg, toks)):
                hit = (len(toks), disp)
                break
        if hit:
            n, disp = hit
            seg = words[i:i + n]
            tail = re.sub(r"^.*?([^A-Za-z0-9]*)$", r"\1", seg[-1]["w"])
            out.append({"w": disp + tail, "s": seg[0]["start"], "e": seg[-1]["end"]})
            i += n
        else:
            w = words[i]
            out.append({"w": w["w"], "s": w["start"], "e": w["end"]})
            i += 1
    return out


def phrases(words, max_words, max_chars):
    ph, cur = [], []
    for k, w in enumerate(words):
        cur.append(w)
        txt = " ".join(x["w"] for x in cur)
        nxt = words[k + 1]["w"] if k + 1 < len(words) else ""
        end_punct = bool(re.search(r"[,.:;?!]$", w["w"]))
        too_long = len(cur) >= max_words or len(txt + " " + nxt) > max_chars
        if end_punct or too_long or k == len(words) - 1:
            ph.append(cur)
            cur = []
    return ph


def srt_time(t):
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def main():
    vo = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
    dur = round(vo["duration"] + CFG.get("extra_tail", 0.0), 3)
    lines, allp, W, T = [], [], {}, {}
    for ln in vo["lines"]:
        ws = substitute(ln["words"], CFG["subs"])
        W[ln["id"]] = [round(w["s"], 3) for w in ws]
        T[ln["id"]] = round(ln["start"], 3)
        T[ln["id"] + "_end"] = round(ln["end"], 3)
        ps = phrases(ws, CFG["max_words"], CFG["max_chars"])
        for p in ps:
            allp.append({"line": ln["id"], "s": round(p[0]["s"], 3), "e": round(p[-1]["e"], 3),
                         "w": [[x["w"], round(x["s"], 3), round(x["e"], 3)] for x in p]})
        lines.append({"id": ln["id"], "s": round(ln["start"], 3), "e": round(ln["end"], 3),
                      "text": " ".join(w["w"] for w in ws)})
    # on/off: a phrase shows from its first word - lead until the next phrase starts (or line end + hold)
    for k, p in enumerate(allp):
        p["on"] = round(max(0.0, p["s"] - CFG.get("lead", 0.08)), 3)
        nxt = allp[k + 1] if k + 1 < len(allp) else None
        hold_end = p["e"] + CFG.get("hold", 0.55)
        p["off"] = round(min(nxt["s"] - CFG.get("lead", 0.08), hold_end) if nxt else min(hold_end, dur), 3)
        if nxt and nxt["line"] == p["line"]:
            p["off"] = round(nxt["s"] - CFG.get("lead", 0.08), 3)
    data = {"key": KEY, "dur": dur, "lines": lines, "phrases": allp, "W": W, "T": T}
    js = "// generated by tools/build.py from vo/data/vo.json; do not edit\nwindow.VO = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(os.path.join(ROOT, "assets", "lib", "timing.js"), "w", encoding="utf-8").write(js)
    # SRT (display text, one cue per phrase)
    srt = []
    for k, p in enumerate(allp, 1):
        srt.append(f"{k}\n{srt_time(p['on'])} --> {srt_time(p['off'])}\n{' '.join(w[0] for w in p['w'])}\n")
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    open(os.path.join(ROOT, "out", KEY + ".srt"), "w", encoding="utf-8").write("\n".join(srt))
    # root duration
    ip = os.path.join(ROOT, "index.html")
    if os.path.exists(ip):
        h = open(ip, encoding="utf-8").read()
        h = re.sub(r'data-duration="[\d.]+"', f'data-duration="{dur}"', h)
        open(ip, "w", encoding="utf-8").write(h)
    print(f"{KEY}: {dur:.2f} s, {len(lines)} lines, {len(allp)} phrases, {sum(len(p['w']) for p in allp)} words")
    for ln in lines:
        print(f"  {ln['id']:>8} {ln['s']:6.2f}-{ln['e']:6.2f}  {ln['text'][:90]}")


main()
