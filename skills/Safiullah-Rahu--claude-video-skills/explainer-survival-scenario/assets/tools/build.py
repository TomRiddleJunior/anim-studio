def norm(s):
    return re.sub(r"[^a-z0-9']", "", s.lower())


def L(i):
    return LINES[i]


def w(i, word, k=0):
    hits = [x for x in LINES[i]["words"] if norm(x["w"]).startswith(norm(word))]
    if not hits:
        raise KeyError(f"{i}:{word}")
    return hits[min(k, len(hits) - 1)]["start"]


def we(i, word, k=0):
    hits = [x for x in LINES[i]["words"] if norm(x["w"]).startswith(norm(word))]
    return hits[min(k, len(hits) - 1)]["end"]


