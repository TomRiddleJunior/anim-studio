"""Generic build step for a survival-scenario reel. Everything is declared in vo/script.json and timed from Kokoro's
word times (vo/data/vo.json), so re-voicing re-times the film.

script.json additions (per line, all optional):
  "shot": "A1"              a new shot starts 0.3 s before this line (the first one at 0); film.js reads FILM_VO.T[shot]
  "caps": [[text, colour]]  one caption phrase per entry, colour r|g|y|w ("|" = line break); words must add up to the line
  "hud": "9:47 PM"          the HUD clock shows/rolls to this time on this line (amber if "hudCol": "y")
  "tags": [{"at": word, "title": "...", "sub": "...", "col": "y|g|r", "until": "shotKey"}]
  "chips": [[word, "LABEL"], ...]   a row of green ✓ chips, one per word
top level: "end": {"q1": "WHAT DID SHE", "q2": "MISS?", "pill": "TELL ME IN THE COMMENTS", "series": "...", "next": "DAY 2",
           "r": 2.8, "s": 2.6}   end card 1 starts 0.4 s after the last word, end card 2 r s later
writes assets/lib/film-vo.js, compositions/hud.html, out/<key>.srt, index.html, score/timing.json

usage: python -I tools/build.py
"""
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEY = os.path.basename(ROOT)
SCRIPT = json.load(open(os.path.join(ROOT, "vo", "script.json"), encoding="utf-8"))
VO = json.load(open(os.path.join(ROOT, "vo", "data", "vo.json"), encoding="utf-8"))
DUR = round(VO["duration"], 2)
LINES = {l["id"]: l for l in VO["lines"]}
SPEC = [l for l in SCRIPT["lines"]]
COL = {"w": "#ffffff", "r": "#ff5a45", "g": "#46d483", "y": "#f7b733"}
END = SCRIPT.get("end", {})


def norm(s):
    return re.sub(r"[^a-z0-9']", "", s.lower())


def w(i, word, k=0):
    hits = [x for x in LINES[i]["words"] if norm(x["w"]).startswith(norm(word))]
    if not hits:
        raise KeyError(f"{i}:{word}")
    return hits[min(k, len(hits) - 1)]["start"]


T = {}
for i, l in enumerate(SPEC):
    if l.get("shot"):
        T[l["shot"]] = 0.0 if i == 0 else round(LINES[l["id"]]["start"] - 0.3, 3)
T["R"] = round(VO["lines"][-1]["end"] + 0.4, 3)
T["S"] = round(T["R"] + END.get("r", 2.8), 3)
order = sorted(T.items(), key=lambda kv: kv[1])
nxt = {k: (order[j + 1][1] if j + 1 < len(order) else DUR) for j, (k, _) in enumerate(order)}

fv = {"dur": DUR, "fps": 30, "T": T, "lines": {l["id"]: {"t0": l["start"], "t1": l["end"], "words": [[x["w"], x["start"], x["end"]] for x in l["words"]]} for l in VO["lines"]}}
open(os.path.join(ROOT, "assets", "lib", "film-vo.js"), "w", encoding="utf-8").write("/* generated by tools/build.py */\nwindow.FILM_VO = " + json.dumps(fv, separators=(",", ":")) + ";\n")

caps = []
for spec in SPEC:
    words = LINES[spec["id"]]["words"]
    k = 0
    for text, col in spec.get("caps", [[spec["text"], "w"]]):
        n = len(text.replace("|", " ").split())
        chunk = words[k:k + n]
        assert len(chunk) == n, (spec["id"], text)
        caps.append({"text": text, "col": col, "t0": chunk[0]["start"], "t1": chunk[-1]["end"]})
        k += n
    assert k == len(words), (spec["id"], k, len(words))
for i, c in enumerate(caps):
    c["on"] = round(max(0.0, c["t0"] - 0.06), 3)
    c["off"] = round(min((caps[i + 1]["t0"] if i + 1 < len(caps) else T["R"]) - 0.04, c["t1"] + 0.7), 3)

els, tl, cues = [], [], []


def clip(eid, t0, t1, inner, cls="", style=""):
    els.append(f'<div class="clip {cls}" id="{eid}" data-start="{t0:.3f}" data-duration="{max(0.05, t1 - t0):.3f}" style="{style}">{inner}</div>')


def pop(eid, t0, t1):
    tl.append(f'tl.fromTo("#{eid} > .in", {{opacity: 0, scale: 0.72}}, {{opacity: 1, scale: 1, duration: 0.24, ease: "back.out(2.2)"}}, {t0:.3f});')
    tl.append(f'tl.to("#{eid} > .in", {{opacity: 0, duration: 0.2, ease: "none"}}, {t1 - 0.2:.3f});')


# HUD clock
times = [(LINES[s["id"]]["start"] if i else 0, s["hud"], s.get("hudCol", "w")) for i, s in enumerate(SPEC) if s.get("hud")]
if times:
    HUD_ON, HUD_OFF = times[0][0] + 0.1, min(T["R"], T.get("Q", T["R"]))
    times[0] = (HUD_ON, times[0][1], times[0][2])
    clip("hudbox", HUD_ON, HUD_OFF, '<div class="in hud"><div class="day"><span class="dot"></span>DAY ' + str(SCRIPT.get("day", 1)) + '</div><div class="time"></div><div class="sub">NIGHT</div></div>')
    tl.append(f'tl.fromTo("#hudbox > .in", {{opacity: 0, x: -24}}, {{opacity: 1, x: 0, duration: 0.35, ease: "power2.out"}}, {HUD_ON:.3f});')
    tl.append(f'tl.to("#hudbox > .in", {{opacity: 0, duration: 0.25}}, {HUD_OFF - 0.25:.3f});')
    for i, (t0, txt, c) in enumerate(times):
        t1 = times[i + 1][0] if i + 1 < len(times) else HUD_OFF
        clip(f"tm{i}", t0, t1, f'<div class="in tm {c}">{html.escape(txt)}</div>', "tmw")
        tl.append(f'tl.fromTo("#tm{i} > .in", {{opacity: 0, y: 22}}, {{opacity: 1, y: 0, duration: 0.28, ease: "power3.out"}}, {t0:.3f});')
        tl.append(f'tl.to("#tm{i} > .in", {{opacity: 0, duration: 0.22}}, {t1 - 0.22:.3f});')
        if i:
            cues.append({"t": round(t0, 3), "type": "clock"})
# tags and chips
n_tag = 0
for spec in SPEC:
    for tg in spec.get("tags", []):
        t0 = w(spec["id"], tg["at"]) - 0.05
        t1 = T[tg["until"]] if tg.get("until") else min(v for k, v in T.items() if v > t0 + 0.5)
        s = f'<div class="in tag {tg.get("col", "y")}"><div class="tt">{html.escape(tg["title"])}</div>' + (f'<div class="ts">{html.escape(tg["sub"])}</div>' if tg.get("sub") else "") + "</div>"
        clip(f"tg{n_tag}", t0, t1, s, "tagw", f"top:{tg.get('top', 330)}px;left:0;right:0;")
        pop(f"tg{n_tag}", t0, t1)
        cues.append({"t": round(t0, 3), "type": "tag", "col": tg.get("col", "y")})
        n_tag += 1
    if spec.get("chips"):
        ts = [w(spec["id"], wd) for wd, _ in spec["chips"]]
        t1 = min(v for k, v in T.items() if v > ts[-1])
        row = '<div class="chiprow">' + "".join(f'<div class="chip" id="ch{n_tag}_{i}">✓ {html.escape(lab)}</div>' for i, (_, lab) in enumerate(spec["chips"])) + "</div>"
        clip(f"chips{n_tag}", ts[0] - 0.05, t1, f'<div class="in">{row}</div>', "tagw", "top:330px;left:0;right:0;")
        tl.append(f'tl.set("#chips{n_tag} > .in", {{opacity: 1}}, {ts[0] - 0.05:.3f});')
        for i, t0 in enumerate(ts):
            tl.append(f'tl.fromTo("#ch{n_tag}_{i}", {{opacity: 0, scale: 0.7}}, {{opacity: 1, scale: 1, duration: 0.22, ease: "back.out(2.4)"}}, {t0:.3f});')
            cues.append({"t": round(t0, 3), "type": "chip"})
        tl.append(f'tl.to("#chips{n_tag} > .in", {{opacity: 0, duration: 0.2}}, {t1 - 0.2:.3f});')
        n_tag += 1
# end cards
E1 = (f'<div class="in end1"><div class="e1a">{html.escape(END.get("q1", "WHAT DID SHE"))}</div><div class="e1b">{html.escape(END.get("q2", "MISS?"))}</div>'
      f'<div class="pill w">{html.escape(END.get("pill", "TELL ME IN THE COMMENTS"))} <span>»</span></div></div>')
clip("end1", T["R"], T["S"], E1, "", "position:absolute;left:0;right:0;top:700px;")
tl.append(f'tl.set("#end1 > .in", {{opacity: 1}}, {T["R"]:.3f});')
tl.append(f'tl.fromTo("#end1 .e1a", {{opacity: 0, y: 30}}, {{opacity: 1, y: 0, duration: 0.3, ease: "power3.out"}}, {T["R"]:.3f});')
tl.append(f'tl.fromTo("#end1 .e1b", {{opacity: 0, scale: 1.25}}, {{opacity: 1, scale: 1, duration: 0.3, ease: "power3.out"}}, {T["R"] + 0.18:.3f});')
tl.append(f'tl.fromTo("#end1 .pill", {{opacity: 0, y: 16}}, {{opacity: 1, y: 0, duration: 0.3, ease: "power2.out"}}, {T["R"] + 0.6:.3f});')
tl.append(f'tl.to("#end1 > .in", {{opacity: 0, duration: 0.3}}, {T["S"] - 0.3:.3f});')
E2 = (f'<div class="in end2"><div class="glow"></div><div class="e2a">{html.escape(END.get("series", "THE FIRE TOWER"))}</div><div class="e2b">{html.escape(END.get("next", "DAY 2"))}</div>'
      f'<div class="pill r">FOLLOW FOR {html.escape(END.get("next", "DAY 2"))}</div></div>')
clip("end2", T["S"], DUR, E2, "", "position:absolute;left:0;right:0;top:640px;")
tl.append(f'tl.fromTo("#end2 > .in", {{opacity: 0, scale: 0.94}}, {{opacity: 1, scale: 1, duration: 0.5, ease: "power2.out"}}, {T["S"]:.3f});')
cues += [{"t": T["R"], "type": "endcard"}, {"t": T["S"], "type": "endcard2"}]
for i, c in enumerate(caps):
    txt = "<br>".join(html.escape(p) for p in c["text"].split("|"))
    clip(f"cp{i}", c["on"], c["off"], f'<div class="in cap" style="color:{COL[c["col"]]}">{txt}</div>', "capw")
    tl.append(f'tl.fromTo("#cp{i} > .in", {{opacity: 0, y: 10}}, {{opacity: 1, y: 0, duration: 0.12, ease: "power2.out"}}, {c["on"]:.3f});')
    tl.append(f'tl.to("#cp{i} > .in", {{opacity: 0, duration: 0.08, ease: "none"}}, {c["off"] - 0.08:.3f});')

CSS = open(os.path.join(ROOT, "tools", "hud.css"), encoding="utf-8").read()
hud = (f'<template>\n  <style>{CSS}</style>\n  <div id="root" data-composition-id="hud" data-width="1080" data-height="1920" data-layout-allow-overflow data-layout-allow-overlap>\n'
       + "\n".join("    " + e for e in els) + '\n  </div>\n  <script>\n    (function () {\n      const tl = gsap.timeline({ paused: true });\n'
       + "\n".join("      " + x for x in tl) + '\n      window.__timelines["hud"] = tl;\n    })();\n  </script>\n</template>\n')
open(os.path.join(ROOT, "compositions", "hud.html"), "w", encoding="utf-8").write(hud)


def ts(t):
    h, r = divmod(t, 3600)
    m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{int(s):02d},{int(round((s % 1) * 1000)):03d}"


os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
with open(os.path.join(ROOT, "out", KEY + ".srt"), "w", encoding="utf-8") as f:
    for i, c in enumerate(caps, 1):
        f.write(f"{i}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{c['text'].replace('|', ' ')}\n\n")
idx = open(os.path.join(ROOT, "tools", "index.tmpl.html"), encoding="utf-8").read().replace("{DUR}", str(DUR))
open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(idx)
os.makedirs(os.path.join(ROOT, "score"), exist_ok=True)
json.dump({"T": T, "caps": caps, "dur": DUR, "cues": sorted(cues, key=lambda c: c["t"])}, open(os.path.join(ROOT, "score", "timing.json"), "w", encoding="utf-8"), indent=1)
print(f"duration {DUR} s · {len(caps)} captions · shots " + ", ".join(f"{k} {v:.2f}" for k, v in order))
